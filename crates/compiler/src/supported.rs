//! The LaTeX this compiler implements, as data.
//!
//! `flashtex-compiler --supported [json|markdown|coverage]` prints this
//! inventory. The names are not a hand-maintained promise: text commands come
//! from `parser::BUILT_INS`, math symbols from `math::COMMAND_GLYPHS`,
//! operator names from `math::OPERATOR_NAMES` and math grids from
//! `math::GRID_ENVIRONMENTS`. The dispatch arms that have no constant of their
//! own (math structures, text environments, layout-neutral packages) are
//! listed below, and `tests/supported_latex.rs` scans the real `match` arms in
//! `src/parser.rs` and `src/math.rs` so the two cannot drift. The same test
//! compiles every listed name through the protocol and fails if any of them
//! produces a "not supported" diagnostic, and checks that the generated
//! `docs/user/compiler.md` section and `supported/*` files are current.
//!
//! Coverage is measured against `supported/canonical-latex.tsv`, a vendored
//! list regenerated by `scripts/canonical_latex.py` from the LaTeX2e
//! reference manual index and the package sources, confirmed by pdfLaTeX.
//! "Supported" means "handled without an unsupported diagnostic"; it is not a
//! claim of typographic fidelity (see the descriptions for approximations).

use crate::json::{write_number_into, write_string_into};
use crate::{math, parser};

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Mode {
    Text,
    Math,
}

impl Mode {
    pub fn as_str(self) -> &'static str {
        match self {
            Mode::Text => "text",
            Mode::Math => "math",
        }
    }
}

/// Where in the compiler a command is recognised.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Origin {
    /// A `parser::Parser::command` dispatch arm.
    TextDispatch,
    /// `parser::style_command` / `parser::style_declaration` (face).
    TextStyle,
    /// A font-size declaration (`\tiny` .. `\Huge`).
    TextSize,
    /// Recognised by the lexer or the math atom reader, not by name dispatch.
    ControlSymbol,
    /// A `math::MathParser::command_atom` arm or an infix/limits switch.
    MathStructure,
    /// `math::COMMAND_GLYPHS`.
    MathSymbol,
    /// `math::OPERATOR_NAMES`.
    MathOperator,
    /// Executed by the expansion pass (`crate::expansion`): a TeX/LaTeX
    /// primitive or kernel macro of `flashtex-tex-expansion`, never seen by
    /// the parser.
    Expansion,
}

impl Origin {
    pub fn as_str(self) -> &'static str {
        match self {
            Origin::TextDispatch => "text_dispatch",
            Origin::TextStyle => "text_style",
            Origin::TextSize => "text_size",
            Origin::ControlSymbol => "control_symbol",
            Origin::MathStructure => "math_structure",
            Origin::MathSymbol => "math_symbol",
            Origin::MathOperator => "math_operator",
            Origin::Expansion => "expansion",
        }
    }
}

#[derive(Clone, Debug, PartialEq)]
pub struct Command {
    /// Without the backslash; the line break `\\` is the name `\`.
    pub name: &'static str,
    pub mode: Mode,
    pub origin: Origin,
    /// Argument shape, e.g. `{key}` or `[options]{class}`.
    pub arguments: &'static str,
    pub description: String,
    pub glyph: Option<&'static str>,
    /// False for arms that parse the command but always diagnose that its
    /// output is unavailable (`\check`, `\breve`); excluded from coverage.
    pub renders: bool,
}

#[derive(Clone, Debug, PartialEq)]
pub struct Environment {
    pub name: &'static str,
    pub mode: Mode,
    pub description: String,
}

#[derive(Clone, Debug, PartialEq)]
pub struct Package {
    pub name: &'static str,
    /// The options under which loading the package is silent.
    pub options: &'static str,
    pub description: &'static str,
}

pub struct Inventory {
    pub commands: Vec<Command>,
    pub environments: Vec<Environment>,
    pub packages: Vec<Package>,
}

/// Text commands that have a dispatch arm but only ever emit a diagnostic.
///
/// `thanks` and `and` are meaningful only inside a `\title`/`\author`/`\date`
/// argument, where `strip_thanks` and the `\and` author split consume them.
/// They used to sit in a separate `TEXT_CONTEXT_ONLY` list documented as
/// "on their own they are diagnosed", which was not true: neither had an arm,
/// so both reached `parser::P::unsupported`, whose `debug_assert` on
/// `BUILT_INS` panicked the debug build instead. They now have arms that
/// really do diagnose, which is what this list means.
///
/// `today` was in that list too, and was wrong for a further reason: it
/// renders in ordinary body text like any other kernel macro, so it is an
/// inventory entry rather than a diagnostic.
pub const TEXT_DIAGNOSTIC_ONLY: &[&str] = &["frac", "sqrt", "thanks", "and"];

