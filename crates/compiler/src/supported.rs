fn text_description(name: &str) -> String {
    if let Some((_, command)) = crate::text_builtins::TEXT_SYMBOLS
        .iter()
        .find(|(n, _)| *n == name)
    {
        let glyph = |enc| match crate::text_builtins::text_symbol(name, enc) {
            Some(crate::text_builtins::SymbolOutcome::Char(c)) => c.to_string(),
            Some(crate::text_builtins::SymbolOutcome::Text(t)) => t,
            _ => "unavailable".to_string(),
        };
        use flashtex_tex_text_encoding::encoding::Encoding;
        return format!(
            "text symbol {command}: OT1 {}, T1 {} (tex-text-encoding; unavailable is a LaTeX error)",
            glyph(Encoding::OT1),
            glyph(Encoding::T1)
        );
    }
    text_description_static(name).to_string()
}

fn text_description_static(name: &str) -> &'static str {
    TEXT_COMMANDS
        .iter()
        .find(|(n, ..)| *n == name)
        .map(|(_, _, d)| *d)
        .unwrap_or("")
}

fn text_arguments(name: &str) -> &'static str {
    TEXT_COMMANDS
        .iter()
        .find(|(n, ..)| *n == name)
        .map(|(_, a, _)| *a)
        .unwrap_or("")
}

pub fn inventory() -> Inventory {
    let mut commands = Vec::new();
    for &name in parser::BUILT_INS.iter().chain(TEXT_EXTRA_ARMS) {
        if TEXT_DIAGNOSTIC_ONLY.contains(&name) {
            continue;
        }
        let origin = if SIZE_DECLARATIONS.contains(&name) {
            Origin::TextSize
        } else if parser::style_command(name) || parser::style_declaration(name) {
            Origin::TextStyle
        } else {
            Origin::TextDispatch
        };
        commands.push(Command {
            name,
            mode: Mode::Text,
            origin,
            arguments: text_arguments(name),
            description: text_description(name),
            glyph: None,
            renders: true,
        });
    }
    for &(name, arguments, description) in EXPANSION_COMMANDS {
        commands.push(Command {
            name,
            mode: Mode::Text,
            origin: Origin::Expansion,
            arguments,
            description: description.to_string(),
            glyph: None,
            renders: true,
        });
    }
    for &(name, mode, description) in CONTROL_SYMBOLS {
        commands.push(Command {
            name,
            mode,
            origin: Origin::ControlSymbol,
            arguments: "",
            description: description.to_string(),
            glyph: None,
            renders: true,
        });
    }
    for &(names, arguments, description, renders) in MATH_STRUCTURES {
        for &name in names {
            commands.push(Command {
                name,
                mode: Mode::Math,
                origin: Origin::MathStructure,
                arguments,
                description: description.to_string(),
                glyph: None,
                renders,
            });
        }
    }
    for &(name, glyph) in math::COMMAND_GLYPHS {
        // A `command_atom` arm runs before the glyph table (`\varnothing`
        // keeps `∅` but forces msbm10's advance), so the structure entry
        // above already describes it.
        if MATH_STRUCTURES
            .iter()
            .any(|(names, ..)| names.contains(&name))
            || crate::amssymb::by_name(name).is_some()
        {
            continue;
        }
        commands.push(Command {
            name,
            mode: Mode::Math,
            origin: Origin::MathSymbol,
            arguments: "",
            description: format!("symbol {glyph}"),
            glyph: Some(glyph),
            renders: true,
        });
    }
    // amssymb/amsfonts symbols (`crate::amssymb`), which take precedence over
    // the glyph rows above for the names both list.
    for name in crate::amssymb::command_names() {
        if MATH_STRUCTURES.iter().any(|(names, ..)| names.contains(&name)) {
            continue;
        }
        let ams = crate::amssymb::by_name(name).expect("a listed amssymb command");
        let font = match ams.font {
            crate::amssymb::SymbolFont::Msam => "msam",
            crate::amssymb::SymbolFont::Msbm => "msbm",
        };
        let class = format!("{:?}", ams.class).to_lowercase();
        // Which `\usepackage` the document has to load: base LaTeX2e defines
        // none of these names, and `math::command_atom` diagnoses the command
        // when its package is absent, so the inventory has to say so.
        let package = match ams.provider {
            crate::amssymb::Provider::Amsfonts => "amsfonts",
            crate::amssymb::Provider::Amssymb => "amssymb",
        };
        commands.push(Command {
            name,
            mode: Mode::Math,
            origin: Origin::MathSymbol,
            arguments: "",
            description: format!(
                "symbol {} (\\math{class}, {font} \"{:02X}; needs {package})",
                ams.text, ams.slot
            ),
            glyph: Some(ams.text),
            renders: true,
        });
    }
    for &name in math::OPERATOR_NAMES {
        commands.push(Command {
            name,
            mode: Mode::Math,
            origin: Origin::MathOperator,
            arguments: "",
            description: "upright operator name".to_string(),
            glyph: None,
            renders: true,
        });
    }

    let mut environments: Vec<Environment> = TEXT_ENVIRONMENTS
        .iter()
        .map(|&(name, description)| Environment {
            name,
            mode: Mode::Text,
            description: description.to_string(),
        })
        .collect();
    for &(name, align, left, right) in math::GRID_ENVIRONMENTS {
        let fences = match (left, right) {
            ("", "") => String::new(),
            (l, "") => format!(" with a left {l}"),
            (l, r) => format!(" in {l} {r}"),
        };
        let align = match align {
            'l' => "left-aligned",
            'r' => "right-aligned",
            _ => "centred",
        };
        environments.push(Environment {
            name,
            mode: Mode::Math,
            description: format!("math grid, {align} cells{fences}"),
        });
    }

    let packages = PACKAGES
        .iter()
        .map(|&(name, options, description)| Package {
            name,
            options,
            description,
        })
        .collect();

    Inventory {
        commands,
        environments,
        packages,
    }
}

/// One canonical set and kind with the supported names found in it.
#[derive(Clone, Debug, PartialEq)]
pub struct CoverageRow {
    pub set: &'static str,
    pub kind: &'static str,
    pub canonical: Vec<&'static str>,
    pub supported: Vec<&'static str>,
}

impl CoverageRow {
    pub fn percent(&self) -> f64 {
        percent(self.supported.len(), self.canonical.len())
    }
}

fn percent(part: usize, whole: usize) -> f64 {
    if whole == 0 {
        0.0
    } else {
        (1000.0 * part as f64 / whole as f64).round() / 10.0
    }
}

/// `(set, kind, name)` rows of the canonical list.
pub fn canonical_entries() -> Vec<(&'static str, &'static str, &'static str)> {
    CANONICAL_TSV
        .lines()
        .filter(|line| !line.starts_with('#') && !line.trim().is_empty())
        .filter_map(|line| {
            let mut fields = line.split('\t');
            Some((fields.next()?, fields.next()?, fields.next()?))
        })
        .collect()
}

/// `# Engine:` and `# Source ...:` header lines, without the `# `.
pub fn canonical_sources() -> Vec<&'static str> {
    CANONICAL_TSV
        .lines()
        .filter_map(|line| line.strip_prefix("# "))
        .filter(|line| line.starts_with("Engine:") || line.starts_with("Source "))
        .collect()
}

pub fn coverage(inventory: &Inventory) -> Vec<CoverageRow> {
    let entries = canonical_entries();
    let mut rows = Vec::new();
    for &set in CANONICAL_SETS {
        for kind in ["command", "environment"] {
            let canonical: Vec<&'static str> = entries
                .iter()
                .filter(|(s, k, _)| *s == set && *k == kind)
                .map(|(_, _, name)| *name)
                .collect();
            if canonical.is_empty() {
                continue;
            }
            let supported = canonical
                .iter()
                .copied()
                .filter(|name| {
                    if kind == "command" {
                        inventory
                            .commands
                            .iter()
                            .any(|command| command.renders && command.name == *name)
                    } else {
                        inventory.environments.iter().any(|env| env.name == *name)
                    }
                })
                .collect();
            rows.push(CoverageRow {
                set,
                kind,
                canonical,
                supported,
            });
        }
    }
    rows
}

fn totals(rows: &[CoverageRow]) -> (usize, usize) {
    rows.iter().fold((0, 0), |(s, c), row| {
        (s + row.supported.len(), c + row.canonical.len())
    })
}

// ---- rendering ---------------------------------------------------------

fn json_str(s: &str) -> String {
    let mut out = String::new();
    write_string_into(s, &mut out);
    out
}

/// Pretty, one-entry-per-line JSON (stable for review diffs).
pub fn render_json(inventory: &Inventory) -> String {
    let mut out = String::new();
    out.push_str("{\n");
    out.push_str("  \"schema\": \"flashtex-supported-latex/1\",\n");
    out.push_str("  \"generator\": \"flashtex-compiler --supported json\",\n");
    out.push_str(&format!(
        "  \"compiler_version\": {},\n",
        json_str(env!("CARGO_PKG_VERSION"))
    ));
    out.push_str(
        "  \"unsupported_behaviour\": \"any other command produces an explicit 'not supported' diagnostic naming it\",\n",
    );
    out.push_str("  \"commands\": [\n");
    let lines: Vec<String> = inventory
        .commands
        .iter()
        .map(|c| {
            let mut line = format!(
                "    {{\"name\": {}, \"mode\": \"{}\", \"origin\": \"{}\", \"arguments\": {}, \"description\": {}, \"renders\": {}",
                json_str(c.name),
                c.mode.as_str(),
                c.origin.as_str(),
                json_str(c.arguments),
                json_str(&c.description),
                c.renders
            );
            if let Some(glyph) = c.glyph {
                line.push_str(&format!(", \"glyph\": {}", json_str(glyph)));
            }
            line.push('}');
            line
        })
        .collect();
    out.push_str(&lines.join(",\n"));
    out.push_str("\n  ],\n  \"environments\": [\n");
    let lines: Vec<String> = inventory
        .environments
        .iter()
        .map(|e| {
            format!(
                "    {{\"name\": {}, \"mode\": \"{}\", \"description\": {}}}",
                json_str(e.name),
                e.mode.as_str(),
                json_str(&e.description)
            )
        })
        .collect();
    out.push_str(&lines.join(",\n"));
    out.push_str("\n  ],\n  \"packages\": [\n");
    let lines: Vec<String> = inventory
        .packages
        .iter()
        .map(|p| {
            format!(
                "    {{\"name\": {}, \"silent_options\": {}, \"description\": {}}}",
                json_str(p.name),
                json_str(p.options),
                json_str(p.description)
            )
        })
        .collect();
    out.push_str(&lines.join(",\n"));
    out.push_str("\n  ],\n  \"coverage\": {\n    \"sources\": [\n");
    let lines: Vec<String> = canonical_sources()
        .iter()
        .map(|s| format!("      {}", json_str(s)))
        .collect();
    out.push_str(&lines.join(",\n"));
    out.push_str("\n    ],\n    \"rows\": [\n");
    let rows = coverage(inventory);
    let lines: Vec<String> = rows
        .iter()
        .map(|row| {
            let mut pct = String::new();
            write_number_into(row.percent(), &mut pct);
            format!(
                "      {{\"set\": \"{}\", \"kind\": \"{}\", \"canonical\": {}, \"supported\": {}, \"percent\": {}}}",
                row.set,
                row.kind,
                row.canonical.len(),
                row.supported.len(),
                pct
            )
        })
        .collect();
    out.push_str(&lines.join(",\n"));
    let (supported, canonical) = totals(&rows);
    let mut pct = String::new();
    write_number_into(percent(supported, canonical), &mut pct);
    out.push_str(&format!(
        "\n    ],\n    \"total\": {{\"canonical\": {canonical}, \"supported\": {supported}, \"percent\": {pct}}}\n  }}\n}}\n"
    ));
    out
}

fn md_code(name: &str) -> String {
    format!("`\\{}`", name.replace('|', "\\|"))
}

fn md_cell(text: &str) -> String {
    text.replace('|', "\\|")
}

/// The coverage table alone, for README benchmark sections.
pub fn render_coverage_markdown(inventory: &Inventory) -> String {
    let rows = coverage(inventory);
    let mut out = String::new();
    out.push_str("| Canonical set | Commands supported | Environments supported |\n");
    out.push_str("| --- | ---: | ---: |\n");
    for &set in CANONICAL_SETS {
        let cell = |kind: &str| match rows.iter().find(|r| r.set == set && r.kind == kind) {
            Some(row) => format!(
                "{}/{} ({:.1}%)",
                row.supported.len(),
                row.canonical.len(),
                row.percent()
            ),
            None => "none defined".to_string(),
        };
        out.push_str(&format!(
            "| {} | {} | {} |\n",
            set,
            cell("command"),
            cell("environment")
        ));
    }
    let (supported, canonical) = totals(&rows);
    out.push_str(&format!(
        "| **total** | **{}/{} ({:.1}%)** | |\n",
        supported,
        canonical,
        percent(supported, canonical)
    ));
    out.push_str(
        "\nGenerated by `flashtex-compiler --supported coverage` against \
         `crates/compiler/supported/canonical-latex.tsv` (LaTeX2e reference-manual index and \
         package sources, each name confirmed by pdfLaTeX; TeX Live 2026). The total row counts \
         commands and environments together. Supported means handled without an unsupported \
         diagnostic, not typographic parity.\n",
    );
    // #254 added this caveat to `supported/coverage.md` by hand. That file is
    // generated, so the note broke `generated_artifacts_are_current` and the
    // next regeneration would have silently deleted it. It belongs here, where
    // regeneration reproduces it.
    out.push_str(
        "\n**The denominator excludes math-mode symbol commands entirely.** `canonical-latex.tsv`'s candidates are `@findex`/`@EnvIndex` entries from the LaTeX2e reference manual plus each listed package's own source files (see `crates/compiler/scripts/canonical_latex.py`'s header); math symbols such as `\\alpha` and `\\odot` are neither in that manual's index nor in any of the nine package source lists, so they never become candidates and are absent from the table. The compiler tracks math-command support separately (`crates/compiler/src/math.rs`'s `COMMAND_GLYPHS`/`OPERATOR_NAMES`, `crates/compiler/src/supported.rs`'s `Origin::MathSymbol`/`MathOperator`/`MathStructure`; the full list is in `docs/user/compiler.md`'s math tables), but `--supported coverage` does not count them.\n",
    );
    out
}

pub const DOC_BEGIN: &str =
    "<!-- BEGIN GENERATED supported-latex: `flashtex-compiler --supported markdown`; do not edit by hand -->";
pub const DOC_END: &str = "<!-- END GENERATED supported-latex -->";

/// The "Supported LaTeX" section of `docs/user/compiler.md`, markers included.
pub fn render_markdown(inventory: &Inventory) -> String {
    let mut out = String::new();
    out.push_str(DOC_BEGIN);
    out.push_str("\n## Supported LaTeX\n\n");
    let text = inventory
        .commands
        .iter()
        .filter(|c| c.mode == Mode::Text)
        .count();
    let math = inventory
        .commands
        .iter()
        .filter(|c| c.mode == Mode::Math)
        .count();
    out.push_str(&format!(
        "This compiler implements a finite LaTeX subset: {} text-mode and {} math-mode command \
         entries, {} environments and {} layout-neutral packages. Every other command produces \
         an explicit \"not supported\" diagnostic naming it, and every other environment or \
         package a warning; nothing is dropped silently. Descriptions note approximations. \
         Outstanding features with reproductions are in `crates/compiler/UNSUPPORTED.md`.\n\n",
        text,
        math,
        inventory.environments.len(),
        inventory.packages.len()
    ));
    out.push_str(
        "Regenerate with `crates/compiler/scripts/render_supported_latex.sh`; \
         `cargo test --test supported_latex` fails when this section is stale.\n\n",
    );

    out.push_str("### Coverage\n\n");
    out.push_str(&render_coverage_markdown(inventory));
    out.push_str("\nCanonical sources:\n\n");
    for source in canonical_sources() {
        out.push_str(&format!("- {}\n", source));
    }

    let table = |out: &mut String, title: &str, filter: &dyn Fn(&Command) -> bool| {
        out.push_str(&format!(
            "\n### {title}\n\n| Command | Arguments | Behaviour |\n| --- | --- | --- |\n"
        ));
        for c in inventory.commands.iter().filter(|c| filter(c)) {
            let arguments = if c.arguments.is_empty() {
                String::new()
            } else {
                format!("`{}`", md_cell(c.arguments))
            };
            out.push_str(&format!(
                "| {} | {} | {} |\n",
                md_code(c.name),
                arguments,
                md_cell(&c.description)
            ));
        }
    };
    table(&mut out, "Text commands", &|c| {
        c.mode == Mode::Text && c.origin != Origin::Expansion
    });
    table(&mut out, "Commands run by the expansion pass", &|c| {
        c.origin == Origin::Expansion
    });
    table(&mut out, "Math structures", &|c| {
        c.mode == Mode::Math && matches!(c.origin, Origin::MathStructure | Origin::ControlSymbol)
    });

    out.push_str("\n### Math symbols\n\n");
    let symbols: Vec<String> = inventory
        .commands
        .iter()
        .filter(|c| c.origin == Origin::MathSymbol)
        .map(|c| format!("{} {}", md_code(c.name), c.glyph.unwrap_or("")))
        .collect();
    out.push_str(&symbols.join(", "));
    out.push_str(".\n\n### Operator names\n\nTypeset as upright words: ");
    let operators: Vec<String> = inventory
        .commands
        .iter()
        .filter(|c| c.origin == Origin::MathOperator)
        .map(|c| md_code(c.name))
        .collect();
    out.push_str(&operators.join(", "));
    out.push_str(
        ".\n\n### Environments\n\n| Environment | Mode | Behaviour |\n| --- | --- | --- |\n",
    );
    for e in &inventory.environments {
        out.push_str(&format!(
            "| `{}` | {} | {} |\n",
            e.name,
            e.mode.as_str(),
            md_cell(&e.description)
        ));
    }
    out.push_str("\n### Packages loaded without a warning\n\n| Package | Options | Why it is silent |\n| --- | --- | --- |\n");
    for p in &inventory.packages {
        out.push_str(&format!(
            "| `{}` | `{}` | {} |\n",
            p.name,
            p.options,
            md_cell(p.description)
        ));
    }
    out.push_str(
        "\nAny other package, or these packages with other options, is recorded and reported \
         as recognised but not implemented.\n",
    );
    out.push_str(DOC_END);
    out.push('\n');
    out
}
