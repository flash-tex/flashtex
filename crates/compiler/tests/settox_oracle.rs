fn compile(source: &str) -> CompileOutput {
    compile_full(source, LayoutConstraints::default())
}

fn text(output: &CompileOutput) -> String {
    output.pages.iter().flat_map(|p| &p.items).map(|i| i.text.as_str()).collect()
}

/// One document per configuration: every sample measured, its three values
/// printed as `<index>:<wd>,<ht>,<dp>;`.
fn measured(preamble: &str) -> (Vec<Option<(i64, i64, i64)>>, Vec<String>) {
    let mut doc = format!("{preamble}\n\\newlength\\oW\\newlength\\oH\\newlength\\oD\n\\begin{{document}}\n");
    for (i, (_, s)) in SAMPLES.iter().enumerate() {
        doc.push_str(&format!(
            "\\settowidth\\oW{{{s}}}\\settoheight\\oH{{{s}}}\\settodepth\\oD{{{s}}}Q{i}:\\number\\oW,\\number\\oH,\\number\\oD;\n"
        ));
    }
    doc.push_str("\\end{document}\n");
    let out = compile(&doc);
    let text: String = text(&out).split_whitespace().collect();
    let mut values = vec![None; SAMPLES.len()];
    for part in text.split(';') {
        let Some((index, dims)) = part.rsplit_once('Q').map(|(_, r)| r).and_then(|r| r.split_once(':')) else {
            continue;
        };
        let Ok(index) = index.parse::<usize>() else { continue };
        let d: Vec<i64> = dims.split(',').filter_map(|v| v.parse().ok()).collect();
        if let (Some(slot), [w, h, dp]) = (values.get_mut(index), d.as_slice()) {
            *slot = Some((*w, *h, *dp));
        }
    }
    let warnings = out.diagnostics.iter().map(|d| d.message.clone()).filter(|m| m.contains("settoheight") || m.contains("settowidth") || m.contains("settodepth")).collect();
    (values, warnings)
}

fn has_tfm(file: &str) -> bool {
    flashtex_font_resources::discovery::default_tfm_dirs().iter().any(|d| d.join(file).is_file())
}

fn metrics_available() -> bool {
    let out = compile("\\documentclass{article}\\newlength\\oW\\begin{document}\\settowidth\\oW{x}\\number\\oW\\end{document}");
    !out.diagnostics.iter().any(|d| d.message.contains("metrics not found"))
}

#[test]
fn settowidth_height_depth_match_pdflatex_to_the_sp() {
    if !metrics_available() {
        eprintln!("skipped: no TFM metrics found (set FLASHTEX_TFM_DIRS to apps/mac/Fonts/texmf/fonts/tfm/...)");
        return;
    }
    let mut failures = Vec::new();
    let mut checked = 0;
    for (config, preamble) in CONFIGS {
        let (values, warnings) = measured(preamble);
        if !warnings.is_empty() {
            failures.push(format!("{config}: warnings {warnings:?}"));
        }
        for (i, (sample, _)) in SAMPLES.iter().enumerate() {
            let Some(&(_, _, w, h, d)) = EXPECTED.iter().find(|e| e.0 == *config && e.1 == *sample) else {
                continue;
            };
            // OT1 typewriter is Knuth's `cmtt`, which the app bundle does not
            // ship; without it the measurer (like the render pipeline) uses
            // `ec-lmtt`, up to 12 sp off. Checked only where `cmtt` is found.
            if *sample == "texttt" && ["a10", "a11", "a12"].contains(config) && !has_tfm("cmtt10.tfm") {
                eprintln!("{config} {sample}: skipped, cmtt10.tfm not found");
                continue;
            }
            checked += 1;
            match values[i] {
                Some(got) if got == (w, h, d) => {}
                got => failures.push(format!("{config} {sample}: got {got:?}, pdflatex ({w}, {h}, {d})")),
            }
        }
    }
    assert!(checked > 400, "only {checked} rows checked");
    assert!(failures.is_empty(), "{} of {checked} differ:\n{}", failures.len(), failures.join("\n"));
}

