//! `*`, and two hyphenation points inside one ligature -- the constructs the
//! 2026-09-22 parity scoreboard (`docs/evidence/parity-2026-09-22`) found
//! behind "script marker has no preceding math atom" (45 arXiv documents),
//! "duplicate script on a math atom", and the `typeset.rs` byte-range panic
//! of arXiv 2501.07497v1 -- pinned against pdfTeX's glyph origins.
//!
//! * `LEADING`: tex.web §1176 -- a script goes on the tail noad only when
//!   `scripts_allowed(tail)`; after nothing (`$^1$`, `SrTiO$_3$`,
//!   `\mathrm{^{1}}`, `{^r C}`) or after glue (`a\,^2`, `a\quad_i`) TeX
//!   appends an Ord noad with an empty nucleus and sets the script on it.
//!   The compiler dropped the script with an error instead. The same lines
//!   pin `*` in math: plain.tex `\mathcode`\*="2203` makes it cmsy's
//!   `asteriskmath`; the fallback glyph ran 0.6 pt narrow (`Sgr A$^*$ in`).
//! * `GROUPS`: a script after a braced group goes on the group's own Ord
//!   noad, whose nucleus is the boxed list (§1186 unpacks only a lone
//!   unscripted character). Flattening `{r'}^{\,2}` put a second
//!   superscript on `r` ("duplicate script"), and `{ab}^2` would raise the
//!   2 from `b` instead of from the box.
//! * `LIGATURE`: `coefficents` has Liang points after `coef` and `coeff`,
//!   both inside the `ffi` ligature. pdfTeX's reconstitution builds the
//!   discretionary at the first and resumes after the ligature (§913-918:
//!   `\showhyphens` prints `co-ef-fi-cents`; under `\pdfnoligatures` it
//!   prints `co-ef-f-i-cents`). Keeping both points sliced the word with a
//!   next point inside the ligature's range and panicked.
//! * `ARRAY_PAR`: latex.ltx `\@array` runs `\let\par\@empty`, so a blank
//!   line inside `pmatrix`, `cases` or `array` is nothing; the formula's
//!   scan ended the paragraph there and set the rest as text ("math script
//!   marker used outside math mode", arXiv 2501.07667v1).
//!
