#!/usr/bin/env python3
"""Writes props_data.rs from ICU's machine-generated ubidi_props_data.h
(third_party/icu, ICU 78.2): the bidi properties trie and the mirroring
table, the only parts of it that ubidi.cpp's algorithm reads. The arrays
are copied value for value; props.rs's tests compare them with the header
again, so a hand edit or a stale copy fails `cargo test`.

    python3 crates/flashtex-xetex/src/native/ubidi/gen_props_data.py
"""
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[4]
HEADER = ROOT / "third_party/icu/icu-src/source/common/ubidi_props_data.h"


def array(src, ctype, name):
    m = re.search(r"static const %s %s\[(\w+)\]=\{(.*?)\};" % (ctype, name), src, re.S)
    if not m:
        sys.exit(f"{name} not found in {HEADER}")
    vals = [v.strip() for v in m.group(2).replace("\n", "").split(",") if v.strip()]
    if re.fullmatch(r"[0-9]+", m.group(1)):
        assert len(vals) == int(m.group(1)), name
    return vals


def trie_fields(src):
    # The UTrie2 initializer of ubidi_props_singleton: index, data16, data32,
    # indexLength, dataLength, index2NullOffset, dataNullOffset, initialValue,
    # errorValue, highStart, highValueIndex, ...
    m = re.search(r"ubidi_props_singleton=\{.*?\{\s*(.*?)\}", src, re.S)
    fields = [f.strip() for f in m.group(1).replace("\n", "").split(",")]
    assert fields[0] == "ubidi_props_trieIndex", fields
    return {
        "INDEX_LENGTH": fields[3],
        "DATA_LENGTH": fields[4],
        "HIGH_START": fields[9],
        "HIGH_VALUE_INDEX": fields[10],
    }


def rust_array(name, ty, vals):
    lines = []
    for i in range(0, len(vals), 12):
        lines.append("    " + ", ".join(vals[i : i + 12]) + ",")
    return f"pub const {name}: &[{ty}; {len(vals)}] = &[\n" + "\n".join(lines) + "\n];\n"


def main():
    src = HEADER.read_text()
    indexes = array(src, "int32_t", "ubidi_props_indexes")
    trie = array(src, "uint16_t", "ubidi_props_trieIndex")
    mirrors = array(src, "uint32_t", "ubidi_props_mirrors")
    f = trie_fields(src)
    out = [
        "// Generated by gen_props_data.py from ICU 78.2's ubidi_props_data.h\n",
        "// (third_party/icu/icu-src/source/common/), itself machine-generated by\n",
        "// ICU's genprops (icu/tools/unicode/c/genprops/bidipropsbuilder.cpp).\n",
        "// Copyright (C) 2016 and later: Unicode, Inc. and others; Copyright (C)\n",
        "// 1999-2016, International Business Machines Corporation and others.\n",
        "// Unicode License V3 (crates/flashtex-xetex/LICENSE). Do not edit.\n\n",
        rust_array("INDEXES", "i32", indexes),
        "\n",
        f"pub const INDEX_LENGTH: usize = {f['INDEX_LENGTH']};\n",
        f"pub const DATA_LENGTH: usize = {f['DATA_LENGTH']};\n",
        f"pub const HIGH_START: u32 = {f['HIGH_START']};\n",
        f"pub const HIGH_VALUE_INDEX: usize = {f['HIGH_VALUE_INDEX']};\n\n",
        rust_array("TRIE_INDEX", "u16", trie),
        "\n",
        rust_array("MIRRORS", "u32", mirrors),
    ]
    path = HERE / "props_data.rs"
    path.write_text("".join(out))
    # formatted as scripts/gate.sh checks every changed .rs file
    subprocess.run(["rustfmt", "--edition", "2021", str(path)], check=True)


main()
