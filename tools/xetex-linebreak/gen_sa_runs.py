#!/usr/bin/env python3
"""Write crates/flashtex-xetex/src/native/linebreak_sa.rs: the characters
ICU's dictionary break engines take as one run (dictbe.cpp's engine sets,
`[[:Thai:]&[:LineBreak=SA:]]` and its Lao, Myanmar and Khmer counterparts),
and for every other LineBreak=SA character its script, for which ICU has no
engine (`UnhandledEngine`: the run gets no breaks).

From Unicode 17.0.0's UCD, the version of TeX Live 2026's ICU 78.2:

    python3 tools/xetex-linebreak/gen_sa_runs.py LineBreak.txt Scripts.txt > \\
        crates/flashtex-xetex/src/native/linebreak_sa.rs

with LineBreak.txt and Scripts.txt from https://www.unicode.org/Public/17.0.0/ucd/
(sha256 below; the script refuses other files).
"""
import hashlib
import sys

SHA256 = {
    "LineBreak.txt": "e6a18fa91f8f6a6f8e534b1d3f128c21ada45bfe152eb6b1bcc5e15fd8ac92e6",
    "Scripts.txt": "9f5e50d3abaee7d6ce09480f325c706f485ae3240912527e651954d2d6b035bf",
}
# ICULanguageBreakFactory::loadEngineFor's dictionary engines (brkeng.cpp)
ENGINES = {"Thai": "Thai", "Lao": "Lao", "Myanmar": "Myanmar", "Khmer": "Khmer"}


def ranges(path, want=None):
    """(first, last, value) of each data line of a UCD property file."""
    out = []
    for line in open(path, encoding="utf-8"):
        line = line.split("#")[0].strip()
        if not line:
            continue
        cps, value = [x.strip() for x in line.split(";")]
        a, _, b = cps.partition("..")
        if want is None or value == want:
            out.append((int(a, 16), int(b or a, 16), value))
    return out


def main():
    lb, sc = sys.argv[1], sys.argv[2]
    for p, name in ((lb, "LineBreak.txt"), (sc, "Scripts.txt")):
        h = hashlib.sha256(open(p, "rb").read()).hexdigest()
        if h != SHA256[name]:
            sys.exit("%s: sha256 %s, not Unicode 17.0.0's" % (p, h))
    script = {}
    for a, b, v in ranges(sc):
        for c in range(a, b + 1):
            script[c] = v
    rows = []
    for a, b, _ in ranges(lb, "SA"):
        for c in range(a, b + 1):
            s = ENGINES.get(script.get(c, "Unknown"), "Other")
            if rows and rows[-1][1] == c - 1 and rows[-1][2] == s:
                rows[-1][1] = c
            else:
                rows.append([c, c, s])
    print("// @generated by tools/xetex-linebreak/gen_sa_runs.py from Unicode 17.0.0's")
    print("// LineBreak.txt and Scripts.txt (the UCD of ICU 78.2). Do not edit.")
    print()
    print("use super::SaScript;")
    print()
    print("/// The LineBreak=SA characters, in ranges of one script: the engine")
    print("/// (dictbe.cpp) whose set holds them, or `Other` (no engine).")
    print("pub const SA_RANGES: &[(u32, u32, SaScript)] = &[")
    for a, b, s in rows:
        print("    (0x%04X, 0x%04X, SaScript::%s)," % (a, b, s))
    print("];")


if __name__ == "__main__":
    main()
