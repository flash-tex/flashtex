#!/usr/bin/env python3
"""Unicode mode's latency on the bench documents (M3's §1.2 row): instruction
counts, which a shared runner measures reliably, and wall times, which only
the M1-class reference Mac can gate (DESIGN.md §1.2).

    python3 tools/unicode-m3/latency.py --engine BIN [--reference xetex]
        [--host flashtex-host-unicode --client dl3-client] [--runs 3]
        [--counter auto|perf|valgrind|time|none] [--json OUT]

Note (2026-10-21): this was written before the incremental Unicode engine
landed. Its host `edits` and `reopen` are full runs, not §1.2's edit and
reopen rows; those are measured by tools/incr-bench/unicode.py (`--keys`,
`--reopen`, `FLASHTEX_S0_CACHE`), see docs/evidence/unicode-m3-mac-2026-10-21/.
Its preamble edit is still the preamble row.

Unicode mode had no incremental engine then (docs/design/xetex/INCREMENTAL.md):
every compile, a keystroke's included, is a full run of the engine from the
format, so the §1.2 rows reduce to the cost of that run:

* `engine`: one full run of each bench document (tools/unicode-m3/bench/,
  plus `b5-long`, about 300 pages, generated here) with a warm `.aux`, by
  the candidate writing its PDF (FlashTeX's product path writes the display
  list from the same `ship_out`), by the candidate with `-no-pdf`, and by
  TeX Live's xelatex with and without xdvipdfmx (the oracle, for scale);
  plus `startup`, the run of `\\csname @@end\\endcsname` (process start,
  kpathsea, the format's undump: what every keystroke pays first).
  Instructions retired (user space; `perf stat`, else callgrind, else macOS's
  `/usr/bin/time -l`) and wall time, best and median of `--runs`.
* `host` (with `--host` and `--client`): through flashtex-host-unicode's
  socket as the app drives it: open (a cold compile in a new host: the
  reopen row), five edits inside the EDITPOINT paragraph (the edit row; each
  is a full run, from a spare when one is ready) and one preamble edit (the
  preamble row): time to the first page and to DONE, as dl3-client measures
  them from sending COMPILE.

Targets (DESIGN.md §1.2): edit ≤ 16 ms p95 for the edited page (host ≤ 11 ms),
preamble edit ≤ 400 ms to the first page, reopen ≤ 100 ms to the first page.
"""
import argparse
import json
import os
import re
import shutil
import socket
import statistics
import subprocess
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "xetex-lockstep"))
import latex as L  # noqa: E402  (tools/xetex-lockstep/latex.py)

BENCH = os.path.join(HERE, "bench")
LONG = r"""% Unicode bench (M3): about 300 pages of fontspec text, generated by latency.py.
\documentclass{article}
\usepackage{fontspec}
\usepackage{lipsum}
\begin{document}
\section{Start}
The quick brown fox jumps over the lazy dog. EDITPOINT This paragraph is the
one the latency harness edits.
\newcount\benchn
\loop \section{Part \the\benchn}\lipsum[1-150]\advance\benchn 1 \ifnum\benchn<12 \repeat
\end{document}
"""
STARTUP = "\\csname @@end\\endcsname"


def have(cmd):
    return shutil.which(cmd) is not None


def pick_counter(want):
    if want != "auto":
        return want
    if have("perf"):
        r = subprocess.run(["perf", "stat", "-x,", "-e", "instructions:u", "true"],
                           stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, text=True)
        if r.returncode == 0 and re.search(r"^\d+,", r.stderr, re.M):
            return "perf"
    if sys.platform == "darwin":
        return "time"
    if have("valgrind"):
        return "valgrind"
    return "none"


def timed(cmd, cwd, env, stderr=subprocess.DEVNULL):
    """(exit status, wall seconds) of cmd, waited for with wait4: precise,
    unlike subprocess.run with a timeout, which polls every 50 ms."""
    t = time.perf_counter()
    p = subprocess.Popen(cmd, cwd=cwd, env=env, stdout=subprocess.DEVNULL, stderr=stderr)
    _, status, _ = os.wait4(p.pid, 0)
    secs = time.perf_counter() - t
    p.returncode = os.waitstatus_to_exitcode(status)
    return p.returncode, secs


def measured(cmd, cwd, env, counter, timeout=1800):
    """(exit status, seconds, instructions or None) of one run of cmd."""
    t = time.time()
    if counter == "perf":
        out = os.path.join(cwd, ".perf.txt")
        code, secs = timed(["perf", "stat", "-x,", "-e", "instructions:u", "-o", out, "--"] + cmd, cwd, env)
        m = re.search(r"^(\d+),[^,]*,instructions", open(out).read(), re.M)
        return code, secs, int(m.group(1)) if m else None
    if counter == "valgrind":
        # the count under callgrind; the wall time of a separate plain run
        log = os.path.join(cwd, ".callgrind.txt")
        r = subprocess.run(["valgrind", "--tool=callgrind", "--callgrind-out-file=/dev/null",
                            "--trace-children=yes", "--log-file=" + log] + cmd, cwd=cwd, env=env,
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=timeout * 30)
        n = [int(x.replace(",", "")) for x in re.findall(r"Collected : ([\d,]+)", open(log).read())] \
            if os.path.exists(log) else []
        code, secs = timed(cmd, cwd, env)
        return code, secs, sum(n) if n else None
    if counter == "time":
        r = subprocess.run(["/usr/bin/time", "-l"] + cmd, cwd=cwd, env=env,
                           stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, text=True,
                           timeout=timeout)
        secs = time.time() - t
        m = re.search(r"^\s*(\d+)\s+instructions retired", r.stderr, re.M)
        n = int(m.group(1)) if m else None
        return r.returncode, secs, n if n else None
    code, secs = timed(cmd, cwd, env)
    return code, secs, None


def summary(rows):
    secs = [r[1] for r in rows]
    ins = [r[2] for r in rows if r[2] is not None]
    return {"exit": [r[0] for r in rows], "ms_best": round(min(secs) * 1000, 1),
            "ms_median": round(statistics.median(secs) * 1000, 1),
            "instructions_best": min(ins) if ins else None,
            "instructions_median": int(statistics.median(ins)) if ins else None}


def bench_docs(tmp):
    docs = {}
    for fn in sorted(os.listdir(BENCH)):
        if fn.endswith(".tex"):
            docs[fn[:-4]] = open(os.path.join(BENCH, fn), encoding="utf-8").read()
    docs["b5-long"] = LONG
    return docs


def engine_rows(a, engines, fmts, docs, tmp, counter):
    out = {}
    variants = [("candidate", "candidate-pdf", [a for a in L.RUN_ARGS if a != "-no-pdf"]),
                ("candidate", "candidate-no-pdf", L.RUN_ARGS),
                ("reference", "xelatex-no-pdf", L.RUN_ARGS),
                ("reference", "xelatex-pdf", [a for a in L.RUN_ARGS if a != "-no-pdf"])]
    for name, text in docs.items():
        out[name] = {}
        for who, label, args in variants:
            d = os.path.join(tmp, "engine", name, label)
            os.makedirs(d, exist_ok=True)
            with open(os.path.join(d, name + ".tex"), "w", encoding="utf-8") as f:
                f.write(text)
            exe = L.link(engines[who], os.path.join(d, ".bin"), "xelatex")
            env = L.env_for(fmts[who])
            # warm .aux (and the font name cache) first: a keystroke's run
            subprocess.run([exe] + args + [name + ".tex"], cwd=d, env=env,
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            n = 1 if counter == "valgrind" else a.runs
            rows = [measured([exe] + args + [name + ".tex"], d, env, counter) for _ in range(n)]
            out[name][label] = summary(rows)
            print("engine %-18s %-17s %s" % (name, label, out[name][label]), flush=True)
    out["startup"] = {}
    for who, label in (("candidate", "candidate"), ("reference", "xelatex")):
        d = os.path.join(tmp, "engine", "startup", label)
        os.makedirs(d, exist_ok=True)
        exe = L.link(engines[who], os.path.join(d, ".bin"), "xelatex")
        env = L.env_for(fmts[who])
        n = 1 if counter == "valgrind" else a.runs
        rows = [measured([exe] + L.RUN_ARGS + [STARTUP], d, env, counter) for _ in range(n)]
        out["startup"][label] = summary(rows)
        print("engine startup %-10s %s" % (label, out["startup"][label]), flush=True)
    return out


def client_compile(a, sock, root, main):
    r = subprocess.run([a.client, "--socket", sock, "--root", root, "--main", main, "--quiet"],
                       stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, timeout=1800)
    rows = [json.loads(x) for x in r.stdout.splitlines() if x.startswith("{")]
    row = rows[-1] if rows else {}
    return {"status": row.get("status"), "pages": row.get("pages"),
            "first_page_ms": row.get("first_page_ms"), "done_ms": row.get("done_ms")}


def start_host(a, tmp, tag):
    sock = os.path.join(tmp, "h-%s.sock" % tag)
    log = open(os.path.join(tmp, "h-%s.log" % tag), "w")
    env = dict(os.environ)
    env.update(SOURCE_DATE_EPOCH="0", FORCE_SOURCE_DATE="1", TZ="UTC")
    env.setdefault("FLASHTEX_FORMAT_CACHE_DIR", os.path.join(tmp, "format-cache"))
    p = subprocess.Popen([a.host, "--socket", sock], stdout=log, stderr=subprocess.STDOUT, env=env)
    for _ in range(6000):
        if os.path.exists(sock):
            try:
                s = socket.socket(socket.AF_UNIX)
                s.connect(sock)
                s.close()
                break
            except OSError:
                pass
        if p.poll() is not None:
            raise SystemExit("the host exited: see %s" % log.name)
        time.sleep(0.1)
    return p, sock


def host_rows(a, docs, tmp):
    out = {}
    # one host builds (or validates) the format first, so no row pays for it
    p, sock = start_host(a, tmp, "warm")
    w = os.path.join(tmp, "host", "warm")
    os.makedirs(w, exist_ok=True)
    open(os.path.join(w, "main.tex"), "w").write("\\documentclass{article}\\begin{document}x\\end{document}\n")
    client_compile(a, sock, w, "main.tex")
    p.terminate()
    p.wait()
    for name, text in docs.items():
        root = os.path.join(tmp, "host", name)
        os.makedirs(root, exist_ok=True)
        path = os.path.join(root, "main.tex")
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        p, sock = start_host(a, tmp, name)
        try:
            row = {"open": client_compile(a, sock, root, "main.tex")}
            # the .aux exists now; a second open in a new host is the reopen
            p.terminate()
            p.wait()
            p, sock = start_host(a, tmp, name + "-2")
            row["reopen"] = client_compile(a, sock, root, "main.tex")
            edits = []
            for i in range(5):
                time.sleep(0.5)  # let the spare get ready, as between keys
                with open(path, "w", encoding="utf-8") as f:
                    f.write(text.replace("EDITPOINT", "EDITPOINT%s" % ("x" * (i + 1))))
                edits.append(client_compile(a, sock, root, "main.tex"))
            row["edits"] = edits
            with open(path, "w", encoding="utf-8") as f:
                f.write(text.replace("\\begin{document}", "\\newcommand\\benchzz{}\n\\begin{document}", 1))
            row["preamble_edit"] = client_compile(a, sock, root, "main.tex")
        finally:
            p.terminate()
            p.wait()
        fp = [e["first_page_ms"] for e in row["edits"] if e.get("first_page_ms") is not None]
        row["edit_first_page_ms_max"] = max(fp) if fp else None
        out[name] = row
        print("host %-18s open %s reopen %s edits %s preamble %s" % (
            name, row["open"].get("first_page_ms"), row["reopen"].get("first_page_ms"),
            [e.get("first_page_ms") for e in row["edits"]], row["preamble_edit"].get("first_page_ms")),
            flush=True)
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--engine", required=True)
    ap.add_argument("--reference", default="xetex")
    ap.add_argument("--host")
    ap.add_argument("--client")
    ap.add_argument("--runs", type=int, default=3)
    ap.add_argument("--counter", default="auto", choices=("auto", "perf", "valgrind", "time", "none"))
    ap.add_argument("--json")
    a = ap.parse_args(argv)
    counter = pick_counter(a.counter)
    print("instruction counter:", counter, flush=True)
    tmp = tempfile.mkdtemp(prefix="unicode-latency-")
    engines = {"reference": a.reference, "candidate": a.engine}
    fmts = {}
    for who in ("reference", "candidate"):
        d = os.path.join(tmp, "fmt-" + who)
        os.makedirs(d)
        secs, code, _ = L.build_format(engines[who], d)
        print("format (%s): exit %s, %.1f s" % (who, code, secs), flush=True)
        if code != 0:
            return 1
        fmts[who] = d
    docs = bench_docs(tmp)
    res = {"counter": counter, "platform": sys.platform, "runs": a.runs,
           "machine": os.uname().machine, "cpus": os.cpu_count(),
           "engine": engine_rows(a, engines, fmts, docs, tmp, counter)}
    if a.host and a.client:
        res["host"] = host_rows(a, docs, tmp)
    if a.json:
        with open(a.json, "w") as f:
            json.dump(res, f, indent=1)
    shutil.rmtree(tmp, ignore_errors=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
