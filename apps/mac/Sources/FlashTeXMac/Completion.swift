/// Source-aware completion for the editor. `suggestions` is pure (no AppKit)
/// and works on UTF-8 bytes with the caret given in UTF-16 units, so it is
/// safe on non-ASCII text and on caret positions that are out of range or
/// inside a surrogate pair (those yield no suggestions, never a trap).
///
/// Sources, in rank order:
/// 1. `\end{X}` for every `\begin{X}` before the caret that is still open.
/// 2. Commands the compiler supports (`supported`; default list below), the
///    one spelled exactly as typed first, then in table order.
/// 3. Commands typed elsewhere in the document that are not in `supported`,
///    marked "not supported by this compiler version".
/// 4. Environment names (after `\begin{`/`\end{`), labels (after `\ref{`) and
///    citation keys (after `\cite{`) seen in the document.
/// 5. Words longer than 3 characters from the document, frequency-ranked.
///
/// Rust-produced vocabulary (`Metadata`) is consumed only when it is bound to
/// the revision of the text being completed: the runtime-v1 `compile_result`
/// (its `revision` plus the diagnostics naming commands, references and
/// environments) and the preview-controller `complete` reply
/// (`crates/preview-controller/STDIO.md`: project-index labels, citations and
/// declared commands, bound to a `source_versions` map). Metadata from an
/// older revision than the caret's is refused, never shown.
enum Completion {
    enum Kind: Equatable { case command, environment, reference, citation, word }

    struct Suggestion: Equatable {
        /// Display form, e.g. `\section` or `naïve`.
        let label: String
        /// Text that replaces the partial token (`completionRange`).
        let insertText: String
        let kind: Kind
        let detail: String
        /// When set, accepting inserts this instead of `insertText` and places
        /// the caret inside it (one undoable edit).
        var snippet: Snippet? = nil
    }

    /// Replacement text plus the caret position inside it, in UTF-16 units.
    struct Snippet: Equatable {
        let text: String
        let caretUTF16: Int
        /// Further placeholders (UTF-16 offsets into `text`, in Tab order,
        /// after the caret's); the editor visits them with Tab / ⇧Tab.
        var stops: [Int] = []
    }

    static let maxSuggestions = 12

    /// The compiler's command set, decoded from its machine-readable inventory
    /// `crates/compiler/supported/supported-latex.json` (schema
    /// `flashtex-supported-latex/1`, regenerated by `flashtex-compiler
    /// --supported json` and drift-gated in the compiler crate). The file is
    /// bundled as the SwiftPM resource `Resources/supported-latex.json`, kept
    /// byte-identical by `scripts/sync-supported-latex.sh`;
    /// `CompletionTests.testBundledInventoryMatchesTheCompiler` compares the
    /// two by sha256 and `testVocabularyIsGeneratedFromTheInventory` checks
    /// every rendered command is offered exactly once. Nothing here is
    /// written by hand except the snippet overrides.
    enum Vocabulary {
        enum Mode: String, Equatable, Decodable { case text, math }

        /// The inventory's `origin`: which compiler table accepts the command.
        enum Origin: String, Equatable, Decodable {
            case textDispatch = "text_dispatch"
            case textStyle = "text_style"
            case textSize = "text_size"
            case mathStructure = "math_structure"
            case mathSymbol = "math_symbol"
            case mathOperator = "math_operator"
            case controlSymbol = "control_symbol"
            /// Executed by the expansion pass (`crate::expansion`): a
            /// TeX/LaTeX primitive or kernel macro of `flashtex-tex-expansion`
            /// (`\newcounter`, `\setcounter`, `\providecommand`, ...), never
            /// seen by the parser directly.
            case expansion = "expansion"
        }

        struct Entry: Equatable {
            /// Name without the leading backslash; `\\` is the name `\`.
            let name: String
            /// Argument shape shown after the name, e.g. `{key}` or `[options]{class}`.
            let arguments: String
            let description: String
            let mode: Mode
            let origin: Origin
            /// Rendered glyph for a math symbol.
            var glyph: String? = nil
            /// For a command the compiler accepts in both modes (`\textbf`,
            /// `\quad`): the math-mode behaviour, shown after the text one.
            var mathDescription: String? = nil

            var label: String { "\\" + name + arguments }

            /// The argument shape as an insertion: every `{…}` becomes `{}`,
            /// `[…]` optionals are dropped, and the caret lands in the first
            /// braces (`\section{|}`, `\frac{|}{}`, `\newcommand{|}{}`).
            /// Nil for commands without a braced argument.
            var snippet: Completion.Snippet? {
                if let override = Vocabulary.snippetOverrides[name] { return override }
                var out = "\\" + name
                var stops: [Int] = []
                var i = arguments.startIndex
                while i < arguments.endIndex {
                    let c = arguments[i]
                    if c == "[" {
                        i = arguments[i...].firstIndex(of: "]").map(arguments.index(after:)) ?? arguments.endIndex
                    } else if c == "{" {
                        out += "{"
                        stops.append((out as NSString).length)
                        out += "}"
                        i = arguments[i...].firstIndex(of: "}").map(arguments.index(after:)) ?? arguments.endIndex
                    } else {
                        i = arguments.index(after: i)
                    }
                }
                guard let caret = stops.first else { return nil }
                // Tab visits the later braces, then leaves the snippet.
                return Completion.Snippet(text: out, caretUTF16: caret, stops: Array(stops.dropFirst()) + [(out as NSString).length])
            }
            var detail: String {
                switch mode {
                case .text: return mathDescription.map { description + " · in math: " + $0 } ?? description
                case .math: return "math · " + description
                }
            }
        }

        // MARK: hand-written overrides (applied on top of the inventory)

        /// Argument shapes that replace the inventory's `arguments` for the
        /// popup label and snippet. Every key must name an inventory command
        /// (`testVocabularyIsGeneratedFromTheInventory`). Empty today: the
        /// compiler's own shapes (`{num}{den}`, `[index]{x}`, …) are the
        /// snippet patterns.
        static let argumentOverrides: [String: String] = [:]

        /// Whole-snippet overrides for commands whose insertion is not the
        /// brace skeleton of their argument shape.
        static let snippetOverrides: [String: Completion.Snippet] = [
            "left": Completion.Snippet(text: "\\left( \\right)", caretUTF16: 6, stops: [14]),
        ]

        // MARK: the inventory

        /// `flashtex-supported-latex/1`; only the fields the editor uses.
        struct Inventory: Decodable {
            struct Command: Decodable {
                let name: String
                let mode: Mode
                let origin: Origin
                let arguments: String
                let description: String
                var glyph: String? = nil
                let renders: Bool
            }
            struct Environment: Decodable {
                let name: String
                let mode: Mode
                let description: String
            }
            let schema: String
            let generator: String
            let compilerVersion: String
            let commands: [Command]
            let environments: [Environment]

            enum CodingKeys: String, CodingKey { case schema, generator, compilerVersion = "compiler_version", commands, environments }

            static let schema = "flashtex-supported-latex/1"
            static let resourceName = "supported-latex"
            static let resourceExtension = "json"
        }

        /// The bundled inventory, decoded once at first use. A missing or
        /// unreadable resource is logged and yields an empty vocabulary (the
        /// editor keeps working; `make-app.sh` and the tests refuse such a
        /// build).
        static let inventory: Inventory = {
            do {
                return try decodeInventory(loadInventoryData())
            } catch {
                FlashTeXLog.write("completion: supported-latex.json unavailable: \(error)")
                return Inventory(schema: Inventory.schema, generator: "", compilerVersion: "", commands: [], environments: [])
            }
        }()

        enum InventoryError: Error, CustomStringConvertible {
            case missing([String])
            case schema(String)
            var description: String {
                switch self {
                case .missing(let searched): return "resource not found; searched \(searched.joined(separator: ", "))"
                case .schema(let got): return "unexpected schema \(got); expected \(Inventory.schema)"
                }
            }
        }

        static func decodeInventory(_ data: Data) throws -> Inventory {
            let inventory = try JSONDecoder().decode(Inventory.self, from: data)
            guard inventory.schema == Inventory.schema else { throw InventoryError.schema(inventory.schema) }
            return inventory
        }

        /// Candidate locations of `supported-latex.json`, in order: the main
        /// bundle's `Contents/Resources` (the packaged app, where
        /// `make-app.sh` copies it), then the SwiftPM resource bundle
        /// `FlashTeXMac_FlashTeXMac.bundle` beside the executable or the
        /// test bundle (`swift build`, `swift run`, `swift test`). Looked up
        /// by hand rather than through `Bundle.module`, whose accessor traps
        /// when the resource bundle is absent.
        static func inventoryCandidates() -> [URL] {
            let module = Bundle(for: VocabularyBundleMarker.self)
            var out: [URL] = []
            for bundle in [module, Bundle.main] {
                if let url = bundle.url(forResource: Inventory.resourceName, withExtension: Inventory.resourceExtension) { out.append(url) }
            }
            let resourceBundle = "FlashTeXMac_FlashTeXMac.bundle"
            var directories = [module.bundleURL, module.bundleURL.deletingLastPathComponent(), Bundle.main.bundleURL]
            if let exe = Bundle.main.executableURL { directories.append(exe.deletingLastPathComponent()) }
            for directory in directories {
                let url = directory.appendingPathComponent(resourceBundle)
                    .appendingPathComponent(Inventory.resourceName + "." + Inventory.resourceExtension)
                if !out.contains(url) { out.append(url) }
            }
            return out
        }

        static func loadInventoryData() throws -> Data {
            let candidates = inventoryCandidates()
            for url in candidates where FileManager.default.fileExists(atPath: url.path) {
                return try Data(contentsOf: url)
            }
            throw InventoryError.missing(candidates.map(\.path))
        }

        // MARK: derived tables

        /// Every rendered command of the inventory, once each, in offer order:
        /// text-mode commands (dispatch, style and size, in file order), then
        /// math structures, operators and symbols (each in file order).
        /// A command the compiler accepts in both modes is one text entry
        /// carrying the math description; `control_symbol` contributes only
        /// `\\` (the math spacing symbols `\,` `\;` … are not completed).
        static let entries: [Entry] = buildEntries(from: inventory)

        static func buildEntries(from inventory: Inventory) -> [Entry] {
            let rendered = inventory.commands.filter(\.renders)
            let mathDescriptions = Dictionary(rendered.filter { $0.mode == .math }.map { ($0.name, $0.description) }, uniquingKeysWith: { a, _ in a })
            var out: [Entry] = []
            var seen = Set<String>()
            func add(_ c: Inventory.Command, mathDescription: String? = nil) {
                guard seen.insert(c.name).inserted else { return }
                out.append(Entry(name: c.name, arguments: argumentOverrides[c.name] ?? c.arguments, description: c.description,
                                 mode: c.mode, origin: c.origin, glyph: c.glyph, mathDescription: mathDescription))
            }
            for c in rendered where c.mode == .text && c.origin != .controlSymbol { add(c, mathDescription: mathDescriptions[c.name]) }
            for c in rendered where c.origin == .controlSymbol && c.name == "\\" { add(c) }
            for origin in [Origin.mathStructure, .mathOperator, .mathSymbol] {
                for c in rendered where c.origin == origin { add(c) }
            }
            return out
        }

        /// `math_symbol` commands with the glyph the compiler renders, in file order.
        static let symbols: [(String, String)] = entries.filter { $0.origin == .mathSymbol }.map { ($0.name, $0.glyph ?? "") }

        /// `math_operator` commands (`\sin` … `\sgn`), in file order.
        static let operatorNames: [String] = entries.filter { $0.origin == .mathOperator }.map(\.name)

        /// Text/display environments and the math grids the compiler accepts, in file order.
        static let environments: [String] = inventory.environments.map(\.name)

        static let byName: [String: Entry] = Dictionary(entries.map { ($0.name, $0) }, uniquingKeysWith: { a, _ in a })
        static let names: [String] = entries.map(\.name)

        /// Entry for a name outside the table (a caller-supplied list).
        static func generic(_ name: String) -> Entry {
            Entry(name: name, arguments: "", description: "supported by this compiler", mode: .text, origin: .textDispatch)
        }
    }

    /// Anchors `Bundle(for:)` to this module for the inventory lookup.
    private final class VocabularyBundleMarker {}

    static let defaultSupported: [String] = Vocabulary.names

    /// Environments the compiler names explicitly; any other environment
    /// typesets its body as plain text with a warning.
    static let knownEnvironments = Vocabulary.environments

    /// Citation commands whose `{` argument completes citation keys (the
    /// project-index reference set in `crates/project-index/README.md`).
    static let citationCommands = ["cite", "citep", "citet", "citeauthor", "citeyear", "parencite", "textcite", "autocite", "nocite"]

    // MARK: token at the caret

    /// The partial token ending at the caret, as UTF-8 byte offsets into `text`.
    enum Token: Equatable {
        /// `\` followed by `name` (possibly empty, or `\` for `\\`).
        case command(name: String, start: Int, end: Int)
        /// A run of letters, with what immediately precedes it (`\begin{`, `\ref{`, …).
        case word(text: String, start: Int, end: Int, context: Context)

        enum Context: Equatable { case none, beginEnvironment, endEnvironment, reference, citation, label, package, file }

        var start: Int {
            switch self { case .command(_, let s, _), .word(_, let s, _, _): return s }
        }
        var end: Int {
            switch self { case .command(_, _, let e), .word(_, _, let e, _): return e }
        }
    }

    /// Returns nil when the caret is not on a scalar boundary or there is no
    /// token immediately before it.
    static func token(in text: String, caretUTF16: Int) -> Token? {
        guard let caretByte = utf8Offset(of: caretUTF16, in: text) else { return nil }
        return withBytes(text) { b in token(in: b, caretByte: caretByte) }
    }

    private static func token(in b: UnsafeBufferPointer<UInt8>, caretByte: Int) -> Token? {
        guard caretByte <= b.count, let p = b.baseAddress else { return nil }
        if let key = argumentKeyToken(in: b, caretByte: caretByte) { return key }
        let table = wordByteClass
        var start = caretByte
        var asciiLettersOnly = true
        while start > 0, table[Int(p[start - 1])] != 0 {
            if p[start - 1] >= 0x80 { asciiLettersOnly = false }
            start -= 1
        }
        if start == caretByte, caretByte >= 2, b[caretByte - 1] == backslash, b[caretByte - 2] == backslash {
            return .command(name: "\\", start: caretByte - 2, end: caretByte) // `\\`
        }
        if start > 0, b[start - 1] == backslash, asciiLettersOnly {
            let name = String(decoding: b[start..<caretByte], as: UTF8.self)
            return .command(name: name, start: start - 1, end: caretByte)
        }
        let context = context(in: b, before: start)
        // Right after an argument brace (`\ref{`, `\cite{`, …) an empty prefix
        // lists everything; elsewhere there must be letters before the caret.
        if start == caretByte { return context == .none ? nil : .word(text: "", start: start, end: caretByte, context: context) }
        let word = String(decoding: b[start..<caretByte], as: UTF8.self)
        guard word.unicodeScalars.allSatisfy({ $0.properties.isAlphabetic }) else { return nil }
        return .word(text: word, start: start, end: caretByte, context: context)
    }

    /// What the word starting at `start` completes, judged by the argument
    /// opener immediately before it.
    private static func context(in b: UnsafeBufferPointer<UInt8>, before start: Int) -> Token.Context {
        guard start > 0, b[start - 1] == UInt8(ascii: "{") else { return .none }
        if endsWith(b, upTo: start, suffix: "\\begin{") { return .beginEnvironment }
        if endsWith(b, upTo: start, suffix: "\\end{") { return .endEnvironment }
        if endsWith(b, upTo: start, suffix: "\\label{") { return .label }
        if endsWith(b, upTo: start, suffix: "\\ref{") || endsWith(b, upTo: start, suffix: "\\eqref{")
            || endsWith(b, upTo: start, suffix: "\\pageref{") || endsWith(b, upTo: start, suffix: "\\autoref{") {
            return .reference
        }
        if citationCommands.contains(where: { endsWith(b, upTo: start, suffix: "\\" + $0 + "{") }) { return .citation }
        if endsWith(b, upTo: start, suffix: "\\usepackage{") { return .package }
        if fileCommands.contains(where: { endsWith(b, upTo: start, suffix: "\\" + $0 + "{") }) { return .file }
        return .none
    }

    /// Commands whose `{` argument completes a project file path.
    static let fileCommands = ["input", "include", "includegraphics"]

    /// Argument keys are wider than words: `eq:main`, `knuth-84`, `ch/one.tex`,
    /// `amsmath` after a comma. Scanned back from the caret over key bytes to
    /// the argument opener (`{`, or `,` inside a list argument), and only kept
    /// when that opener belongs to a key-taking command; otherwise the plain
    /// word scan applies.
    private static func argumentKeyToken(in b: UnsafeBufferPointer<UInt8>, caretByte: Int) -> Token? {
        let table = wordByteClass
        var start = caretByte
        while start > 0 {
            let c = b[start - 1]
            let key = table[Int(c)] != 0 || (c >= 0x30 && c <= 0x39) || c == UInt8(ascii: ":") || c == UInt8(ascii: "-")
                || c == UInt8(ascii: "_") || c == UInt8(ascii: ".") || c == UInt8(ascii: "/") || c == UInt8(ascii: "+") || c == UInt8(ascii: "*")
            guard key else { break }
            start -= 1
        }
        guard start > 0 else { return nil }
        var opener = start
        if b[start - 1] == UInt8(ascii: ",") { // `\usepackage{a,b`, `\cite{k1,k2`: back to the brace
            var j = start - 1
            while j > 0, b[j - 1] != UInt8(ascii: "{"), b[j - 1] != UInt8(ascii: "\n"), b[j - 1] != UInt8(ascii: "}") { j -= 1 }
            guard j > 0, b[j - 1] == UInt8(ascii: "{") else { return nil }
            opener = j
        }
        let context = context(in: b, before: opener)
        switch context {
        case .reference, .citation, .label, .package, .file:
            let text = String(decoding: b[start..<caretByte], as: UTF8.self)
            guard text.utf8.allSatisfy({ $0 < 0x80 }) || text.unicodeScalars.allSatisfy({ $0.properties.isAlphabetic }) else { return nil }
            return .word(text: text, start: start, end: caretByte, context: context)
        case .none, .beginEnvironment, .endEnvironment:
            return nil
        }
    }

    // MARK: what typing opens on its own

    /// The token at the caret together with its UTF-16 start in the whole text.
    struct CaretToken: Equatable {
        /// What the caret is on. Read this for the token's *kind* — a control
        /// word, or a word and its argument context. Its `start`/`end` are
        /// UTF-8 offsets into the window `caretToken` read, **not** into the
        /// whole text; rebasing them would cost a scan of everything before
        /// the window, which is exactly what this type exists to avoid.
        /// `startUTF16` is the only offset that indexes the whole text.
        let token: Token
        /// UTF-16 offset of the token's first character (its `\` for a control
        /// word) in the whole text.
        let startUTF16: Int
    }

    /// How much text before the caret `caretToken` reads. Every token this
    /// file recognises is short — a control word, or an argument key plus the
    /// `\command{` opener that gives it meaning — so a window this wide gives
    /// the same answer as scanning the whole document, at a cost that does not
    /// grow with it. Only a pathological token (a `\cite{…}` key list longer
    /// than this) is missed, and the miss is one-sided: the list does not open
    /// by itself, ⌃Space still reads the whole text.
    static let caretTokenWindow = 1024

    /// The token at the caret, read from at most `window` UTF-16 units before
    /// it. This is the cheap main-thread gate for automatic completion: it is
    /// O(window), never O(document), so it may run on every keystroke.
    static func caretToken(in text: NSString, caretUTF16: Int, window: Int = caretTokenWindow) -> CaretToken? {
        let caret = max(0, min(caretUTF16, text.length))
        var from = max(0, caret - max(1, window))
        if from > 0, from < text.length { from = text.rangeOfComposedCharacterSequence(at: from).location }
        guard from <= caret else { return nil }
        let slice = text.substring(with: NSRange(location: from, length: caret - from))
        guard let token = token(in: slice, caretUTF16: (slice as NSString).length),
              let ns = slice.nsRange(utf8Bytes: .init(path: "", startByte: token.start, endByte: token.end))
        else { return nil }
        return CaretToken(token: token, startUTF16: from + ns.location)
    }

    /// Whether typing should open the list without an explicit ⌃Space.
    ///
    /// Yes for a control word — including the `\` on its own, which lists the
    /// vocabulary — and for an argument key whose command gives it meaning
    /// (`\begin{`, `\end{`, `\ref{`, `\cite{`, `\label{`, `\usepackage{`,
    /// `\input{`). No for a plain prose word: `wordSuggestions` offers words
    /// counted from the document, which is worth asking for with ⌃Space and is
    /// noise over every fourth letter of a sentence.
    static func opensAutomatically(_ token: Token?) -> Bool {
        switch token {
        case .command: return true
        case .word(_, _, _, let context): return context != .none
        case nil: return false
        }
    }

    // MARK: fuzzy matching

    /// 0 exact, 1 prefix, 2 subsequence (the typed characters appear in order,
    /// `sbs` in `subsection`), nil no match. Subsequence matches need at
    /// least two typed characters.
    static func matchRank(_ candidate: String, prefix: String) -> Int? {
        if prefix.isEmpty { return 1 }
        if candidate == prefix { return 0 }
        if candidate.hasPrefix(prefix) { return 1 }
        guard prefix.utf8.count >= 2 else { return nil }
        var it = candidate.utf8.makeIterator()
        for p in prefix.utf8 {
            var found = false
            while let c = it.next() { if c == p { found = true; break } }
            if !found { return nil }
        }
        return 2
    }

    /// Items whose key matches `prefix`: the exact and prefix matches (in the
    /// given order) when there are any; otherwise the subsequence matches
    /// (`\ref{main}` → `eq:main` only when nothing starts with `main`), so a
    /// typed prefix never has fuzzy rows mixed under it.
    static func fuzzyFilter<T>(_ items: [T], prefix: String, key: (T) -> String) -> [T] {
        var strong: [T] = []
        var weak: [T] = []
        for item in items {
            switch matchRank(key(item), prefix: prefix) {
            case 0?, 1?: strong.append(item)
            case 2?: weak.append(item)
            default: break
            }
        }
        return strong.isEmpty ? weak : strong
    }

    /// UTF-16 range the chosen suggestion replaces: the token before the caret
    /// including a leading `\`, or an empty range at the caret.
    static func completionRange(in text: String, caretUTF16: Int) -> NSRange {
        let length = (text as NSString).length
        let caret = max(0, min(caretUTF16, length))
        guard let token = token(in: text, caretUTF16: caret),
              let ns = text.nsRange(utf8Bytes: .init(path: "", startByte: token.start, endByte: token.end))
        else { return NSRange(location: caret, length: 0) }
        return ns
    }

    // MARK: math mode at the caret

    /// Whether the caret sits in math mode — inside `$…$`, `$$…$$`, `\\(…\\)`,
    /// `\\[…\\]` or a math environment.
    ///
    /// The answer comes from `SyntaxHighlighter`'s own lexer, which already
    /// owns this knowledge (delimiters, nesting depth, verbatim), so there is
    /// no second set of rules to drift. Pass the editor's in-sync model and it
    /// costs one line's worth of lexing; pass nil (tests, any caller without
    /// one) and the text is lexed whole.
    static func isMathMode(in text: NSString, caretUTF16: Int, highlighter: SyntaxHighlighter? = nil) -> Bool {
        guard text.length > 0 else { return false }
        var model = highlighter ?? SyntaxHighlighter()
        if highlighter == nil { model.reset(text) }
        guard model.length == text.length else { return false }
        return model.mode(at: caretUTF16, text: text).isMath
    }

    // MARK: suggestions

    /// Compatibility entry point: the caller asserts that `result` was compiled
    /// from `text` (it is bound as-is). Prefer `suggestions(in:caretUTF16:metadata:)`
    /// with metadata the caller has already bound to the caret's revision.
    static func suggestions(in text: String, caretUTF16: Int, result: RuntimeV1.CompileResult?,
                            supported: [String] = defaultSupported) -> [Suggestion] {
        suggestions(in: text, caretUTF16: caretUTF16, metadata: result.map(Metadata.from), supported: supported)
    }

    /// `metadata` must already be bound to the revision of `text` (see
    /// `Metadata.bound(to:)`); unbound metadata is the caller's bug, never
    /// this function's to detect. `cancelled` is polled between scan phases
    /// so an off-main computation stops early; a cancelled call returns `[]`.
    /// `mathMode` says whether the caret is in math mode (`isMathMode`). The
    /// caller passes it because it can answer cheaply from the editor's own
    /// syntax model; the default, false, keeps the plain text-mode order.
    static func suggestions(in text: String, caretUTF16: Int, metadata: Metadata?,
                            supported: [String] = defaultSupported, projectFiles: [String] = [],
                            mathMode: Bool = false,
                            cancelled: () -> Bool = { false }) -> [Suggestion] {
        guard let token = token(in: text, caretUTF16: caretUTF16), !cancelled() else { return [] }
        let out: [Suggestion]
        switch token {
        case .command(let prefix, _, _):
            out = commandSuggestions(prefix: prefix, tokenStart: token.start, text: text,
                                     metadata: metadata, supported: supported, mathMode: mathMode, cancelled: cancelled)
        case .word(let prefix, _, _, let context):
            guard prefix.unicodeScalars.count >= 2 || context != .none else { return [] }
            switch context {
            case .beginEnvironment, .endEnvironment:
                out = environmentSuggestions(prefix: prefix, tokenStart: token.start, text: text,
                                             closing: context == .endEnvironment, metadata: metadata)
            case .reference:
                out = referenceSuggestions(prefix: prefix, text: text, metadata: metadata)
            case .citation:
                out = citationSuggestions(prefix: prefix, text: text, metadata: metadata)
            case .label:
                out = labelSuggestions(prefix: prefix, tokenStart: token.start, text: text, metadata: metadata)
            case .package:
                out = packageSuggestions(prefix: prefix)
            case .file:
                out = fileSuggestions(prefix: prefix, files: projectFiles)
            case .none:
                out = wordSuggestions(prefix: prefix, tokenStart: token.start, text: text)
            }
        }
        return cancelled() ? [] : out
    }

    private static func commandSuggestions(prefix: String, tokenStart: Int, text: String, metadata: Metadata?,
                                           supported: [String], mathMode: Bool, cancelled: () -> Bool) -> [Suggestion] {
        var out: [Suggestion] = []
        let scan = scanCommands(in: text, tokenStart: tokenStart, prefix: prefix)
        if cancelled() { return [] }
        // 1. Close environments still open at the caret.
        for open in scan.open.reversed() where "end".hasPrefix(prefix) {
            out.append(Suggestion(label: "\\end{\(open.name)}", insertText: "\\end{\(open.name)}", kind: .environment,
                                  detail: "closes \\begin{\(open.name)} at byte \(open.byte)"))
        }
        // 2. The compiler's documented vocabulary, then commands the project
        //    index saw declared at this exact revision. A project declaration
        //    wins over a static entry of the same name (the compiler expands
        //    the user's macro, not a builtin). Within the vocabulary the
        //    command spelled exactly as typed comes first (`\sec` before
        //    `\section`); the rest keep table order.
        //    In math mode the compiler's math commands float above the text
        //    ones — `\\alpha` and `\\approx` are what `\\a` means inside `$…$`,
        //    while the table's text-first order buries them under `\\addvspace`.
        //    The exactly-typed spelling and the project's own declarations stay
        //    on top of both, and in text mode the order is untouched.
        var offered = Set<String>()
        let declared: [String: Metadata.Item] = Dictionary((metadata?.commands ?? []).filter { $0.definitions > 0 }.map { ($0.name, $0) },
                                                           uniquingKeysWith: { a, _ in a })
        let exact = supported.contains(prefix) ? [prefix] : []
        /// 0 the exact spelling, 1 a project declaration, 2 a math command,
        /// 3 everything else. Only consulted when `mathMode` is on.
        var vocabulary: [(suggestion: Suggestion, rank: Int)] = []
        for name in exact + supported where name.hasPrefix(prefix) && offered.insert(name).inserted {
            if let item = declared[name], let metadata {
                vocabulary.append((Suggestion(label: "\\" + name, insertText: "\\" + name, kind: .command,
                                              detail: item.detail(noun: "declared", revision: metadata.revision) + " · overrides the builtin"),
                                   name == prefix ? 0 : 1))
            } else {
                let entry = Vocabulary.byName[name] ?? Vocabulary.generic(name)
                vocabulary.append((Suggestion(label: entry.label, insertText: "\\" + name, kind: .command, detail: entry.detail,
                                              snippet: entry.snippet),
                                   name == prefix ? 0 : entry.mode == .math ? 2 : 3))
            }
        }
        if mathMode {
            // Stable: equal ranks keep the table order they were filled in.
            out += vocabulary.enumerated().sorted { a, b in
                a.element.rank != b.element.rank ? a.element.rank < b.element.rank : a.offset < b.offset
            }.map(\.element.suggestion)
        } else {
            out += vocabulary.map(\.suggestion)
        }
        if let metadata {
            for item in metadata.commands where item.name.hasPrefix(prefix) && item.name != prefix && offered.insert(item.name).inserted {
                out.append(Suggestion(label: "\\" + item.name, insertText: "\\" + item.name, kind: .command,
                                      detail: item.detail(noun: "declared", revision: metadata.revision)))
            }
        }
        // 3. Commands typed in the document that neither the compiler nor the
        //    project declares, with the compiler's own diagnostic when it
        //    named the command at this revision.
        for name in scan.commands where !offered.contains(name) {
            var detail = "not supported by the compiler"
            if let message = metadata?.diagnosticsByCommand[name] { detail += " — " + message }
            out.append(Suggestion(label: "\\" + name, insertText: "\\" + name, kind: .command, detail: detail))
        }
        // 4. Fuzzy fallback: when nothing starts with the prefix, vocabulary
        //    commands whose name contains the typed characters in order
        //    (`\sbs` → `\subsection`).
        if out.isEmpty, prefix.utf8.count >= 2 {
            for name in supported where out.count < maxSuggestions && !offered.contains(name) && matchRank(name, prefix: prefix) == 2 {
                offered.insert(name)
                let entry = Vocabulary.byName[name] ?? Vocabulary.generic(name)
                out.append(Suggestion(label: entry.label, insertText: "\\" + name, kind: .command, detail: entry.detail, snippet: entry.snippet))
            }
        }
        return Array(out.prefix(maxSuggestions))
    }

    /// `\usepackage{` candidates: common CTAN package names (static; the
    /// compiler records packages without implementing them).
    static let knownPackages = [
        "amsmath", "amssymb", "amsthm", "amsfonts", "mathtools", "graphicx", "hyperref", "geometry", "inputenc", "fontenc",
        "babel", "xcolor", "color", "tikz", "pgfplots", "booktabs", "tabularx", "array", "multirow", "longtable", "enumitem",
        "natbib", "biblatex", "cite", "url", "listings", "minted", "float", "caption", "subcaption", "subfig", "setspace",
        "fancyhdr", "titlesec", "microtype", "lmodern", "fontspec", "unicode-math", "siunitx", "physics", "bm", "cleveref",
        "algorithm", "algorithmic", "algorithm2e", "verbatim", "comment", "todonotes", "lipsum", "parskip", "csquotes",
        "textcomp", "wrapfig", "adjustbox", "pdfpages", "xspace", "etoolbox", "ifthen", "calc", "times", "mathptmx",
    ]

    private static func packageSuggestions(prefix: String) -> [Suggestion] {
        let names = fuzzyFilter(knownPackages, prefix: prefix) { $0 }
        return names.prefix(maxSuggestions).map {
            Suggestion(label: $0, insertText: $0, kind: .command, detail: "package (recognised, not implemented by this compiler)")
        }
    }

    /// `\input{`/`\include{`/`\includegraphics{` candidates: the project's
    /// document paths, matched on the path or its basename.
    private static func fileSuggestions(prefix: String, files: [String]) -> [Suggestion] {
        var seen = Set<String>()
        let unique = files.filter { seen.insert($0).inserted }
        let matched = fuzzyFilter(unique, prefix: prefix) { path in
            let base = path.split(separator: "/").last.map(String.init) ?? path
            return matchRank(path, prefix: prefix) != nil ? path : base
        }
        return matched.prefix(maxSuggestions).map {
            Suggestion(label: $0, insertText: $0, kind: .command, detail: "project document")
        }
    }

    private static func environmentSuggestions(prefix: String, tokenStart: Int, text: String, closing: Bool,
                                               metadata: Metadata?) -> [Suggestion] {
        var names: [String] = []
        if closing {
            names += openEnvironments(in: text, beforeByte: tokenStart).reversed().map(\.name)
        }
        names += knownEnvironments
        names += documentEnvironments(in: text)
        var seen = Set<String>()
        var out: [Suggestion] = []
        // Opening an environment inserts its body skeleton with the caret on
        // the (indented) middle line; closing stays the exact name.
        let indent = closing ? "" : lineIndent(in: text, beforeByte: tokenStart)
        for name in fuzzyFilter(names, prefix: prefix, key: { $0 }) where seen.insert(name).inserted {
            var detail = knownEnvironments.contains(name) ? "supported by this compiler" : "seen in this document"
            if let message = metadata?.diagnosticsByEnvironment[name] { detail += " — " + message }
            let snippet = closing ? nil : environmentSnippet(name, indent: indent)
            out.append(Suggestion(label: name, insertText: name + "}", kind: .environment, detail: detail, snippet: snippet))
        }
        return Array(out.prefix(maxSuggestions))
    }

    /// Body skeleton inserted after `\begin{` for `name`: the caret on the
    /// (indented) middle line, or inside the first placeholder of a richer
    /// template (`itemize`/`enumerate` with `\item`, `figure`/`table` with
    /// `\centering`, `\caption{}` and `\label{}`), the later placeholders as
    /// Tab stops. Offsets are UTF-16 into the inserted text, which starts
    /// right after the `\begin{` the user typed.
    static func environmentSnippet(_ name: String, indent: String) -> Snippet {
        let nl = "\n" + indent
        let base = name.hasSuffix("*") ? String(name.dropLast()) : name
        var lines: [String]
        switch base {
        case "itemize", "enumerate": lines = ["\(name)}", "\\item ⟨⟩", "\\end{\(name)}"]
        case "description": lines = ["\(name)}", "\\item[⟨⟩] ⟨⟩", "\\end{\(name)}"]
        case "figure": lines = ["\(name)}", "\\centering", "\\includegraphics[width=0.8\\linewidth]{⟨⟩}", "\\caption{⟨⟩}", "\\label{fig:⟨⟩}", "\\end{\(name)}"]
        case "table": lines = ["\(name)}", "\\centering", "\\begin{tabular}{⟨⟩}", "\\end{tabular}", "\\caption{⟨⟩}", "\\label{tab:⟨⟩}", "\\end{\(name)}"]
        case "align", "gather", "equation", "multline", "flalign", "alignat":
            lines = ["\(name)}", "⟨⟩", "\\end{\(name)}"]
        default: lines = ["\(name)}", "⟨⟩", "\\end{\(name)}"]
        }
        // Placeholders `⟨⟩` become stops (removed from the text).
        var out = ""
        var stops: [Int] = []
        for (i, line) in lines.enumerated() {
            if i > 0 { out += nl }
            var rest = Substring(line)
            while let r = rest.range(of: "⟨⟩") {
                out += rest[..<r.lowerBound]
                stops.append((out as NSString).length)
                rest = rest[r.upperBound...]
            }
            out += rest
        }
        let caret = stops.first ?? (out as NSString).length
        return Snippet(text: out, caretUTF16: caret, stops: Array(stops.dropFirst()) + [(out as NSString).length])
    }

    /// One candidate for `\label{`: a key derived from the enclosing
    /// `\section`/`\subsection` title (`sec:` + kebab-case), made unique against
    /// the document's labels and the project index's labels at this revision.
    private static func labelSuggestions(prefix: String, tokenStart: Int, text: String, metadata: Metadata?) -> [Suggestion] {
        let heading = enclosingHeading(in: text, beforeByte: tokenStart)
        let slug = heading.map { kebabCase($0.title) } ?? ""
        var taken = Set(labels(in: text))
        if let metadata { taken.formUnion(metadata.labels.map(\.name)) }
        // The key's prefix follows the innermost open environment (`fig:`
        // inside figure, `tab:` inside table, `eq:` inside a math display);
        // `sec:` for a heading's own label.
        let (kind, noun) = labelPrefix(forEnvironment: openEnvironments(in: text, beforeByte: tokenStart).last?.name)
        guard !slug.isEmpty || kind != "sec:" else { return [] }
        let base = kind + slug
        var out: [Suggestion] = []
        if !slug.isEmpty {
            var key = base
            var n = 2
            while taken.contains(key) { key = "\(base)-\(n)"; n += 1 }
            if matchRank(key, prefix: prefix) != nil {
                var detail = heading.map { kind == "sec:" ? "unique key for \\\($0.command){\($0.title)}" : "unique \(noun) key under \\\($0.command){\($0.title)}" }
                    ?? "unique \(noun) key"
                if key != base { detail += " (\(base) is taken)" }
                if let metadata { detail += " · checked against \(metadata.labels.count) project label\(metadata.labels.count == 1 ? "" : "s") · revision \(metadata.revision)" }
                out.append(Suggestion(label: key, insertText: key + "}", kind: .reference, detail: detail))
            }
        }
        if kind != "sec:", prefix.isEmpty || kind.hasPrefix(prefix) {
            out.append(Suggestion(label: kind, insertText: kind, kind: .reference, detail: "\(noun) key prefix"))
        }
        return out
    }

    /// Conventional label prefix and noun for the innermost open environment.
    static func labelPrefix(forEnvironment env: String?) -> (String, String) {
        let base = env.map { $0.hasSuffix("*") ? String($0.dropLast()) : $0 } ?? ""
        switch base {
        case "figure", "wrapfigure", "subfigure": return ("fig:", "figure")
        case "table", "tabular", "longtable": return ("tab:", "table")
        case "equation", "align", "gather", "multline", "flalign", "alignat", "eqnarray", "displaymath", "subequations":
            return ("eq:", "equation")
        case "lstlisting", "minted", "algorithm": return ("lst:", "listing")
        case "theorem", "lemma", "proposition", "corollary", "definition": return ("thm:", "theorem")
        default: return ("sec:", "section")
        }
    }

    private static func referenceSuggestions(prefix: String, text: String, metadata: Metadata?) -> [Suggestion] {
        var seen = Set<String>()
        var out: [Suggestion] = []
        for label in labels(in: text) where matchRank(label, prefix: prefix) != nil && seen.insert(label).inserted {
            var detail = "\\label in this document"
            if let metadata, metadata.unresolvedReferences.contains(label) {
                detail += " — undefined when revision \(metadata.revision) compiled"
            }
            out.append(Suggestion(label: label, insertText: label + "}", kind: .reference, detail: detail))
        }
        // Labels the project index knows from other documents of the project.
        if let metadata {
            for item in metadata.labels where matchRank(item.name, prefix: prefix) != nil && seen.insert(item.name).inserted {
                out.append(Suggestion(label: item.name, insertText: item.name + "}", kind: .reference,
                                      detail: item.detail(noun: "defined", revision: metadata.revision)))
            }
        }
        // Exact and prefix matches before subsequence matches, each in source order.
        return Array(fuzzyFilter(out, prefix: prefix, key: \.label).prefix(maxSuggestions))
    }

    /// `\cite{` candidates: `\bibitem` keys of this document, then the
    /// project index's citation keys. Where a key comes from is stated from
    /// the helper-declared document kinds bound to the same snapshot
    /// (`Metadata.documentKinds`), never inferred from a file name: a record
    /// in a declared bibliography, a `\bibitem` in a LaTeX source, a key the
    /// helper did not report a kind for, or a cited key with no definition
    /// (which says how to declare the .bib). Declared-bibliography records
    /// rank first among the index keys, unresolved keys last.
    private static func citationSuggestions(prefix: String, text: String, metadata: Metadata?) -> [Suggestion] {
        var seen = Set<String>()
        var out: [Suggestion] = []
        for key in bibitems(in: text) where matchRank(key, prefix: prefix) != nil && seen.insert(key).inserted {
            out.append(Suggestion(label: key, insertText: key + "}", kind: .citation, detail: "\\bibitem in this document"))
        }
        if let metadata {
            var ranked: [(rank: Int, suggestion: Suggestion)] = []
            for item in metadata.citations where matchRank(item.name, prefix: prefix) != nil && seen.insert(item.name).inserted {
                let (rank, detail) = citationDetail(item, metadata: metadata)
                ranked.append((rank, Suggestion(label: item.name, insertText: item.name + "}", kind: .citation, detail: detail)))
            }
            // Stable: the index's own (sorted) order within a rank.
            out += ranked.enumerated().sorted { a, b in a.element.rank != b.element.rank ? a.element.rank < b.element.rank : a.offset < b.offset }
                .map(\.element.suggestion)
        }
        return Array(fuzzyFilter(out, prefix: prefix, key: \.label).prefix(maxSuggestions))
    }

    /// Rank (0 declared bibliography record, 1 `\bibitem` in a LaTeX source,
    /// 2 kind unknown, 3 unresolved) and detail text for an index citation.
    static func citationDetail(_ item: Metadata.Item, metadata: Metadata) -> (rank: Int, detail: String) {
        var s: String
        var rank: Int
        if item.definitions == 0 {
            rank = 3
            s = "cited but not defined in a declared bibliography source"
            if let declared = metadata.declaredBibliographies, declared.isEmpty {
                s += " (none declared: Project > Document Kinds)"
            }
        } else {
            let path = item.definedIn ?? "project"
            switch metadata.isDeclaredBibliography(item.definedIn) {
            case true?: rank = 0; s = "record in \(path) (declared bibliography)"
            case false?: rank = 1; s = "\\bibitem in \(path)"
            case nil: rank = 2; s = "defined in \(path) (kind not reported by this helper)"
            }
            if item.definitions > 1 { s += " (+\(item.definitions - 1) more)" }
        }
        if item.occurrences > 0 { s += " · \(item.occurrences)\(item.locationsTruncated ? "+" : "") use\(item.occurrences == 1 ? "" : "s")" }
        return (rank, s + " · revision \(metadata.revision)")
    }

    private static func wordSuggestions(prefix: String, tokenStart: Int, text: String) -> [Suggestion] {
        let counts = wordFrequencies(in: text, prefix: prefix, excludingTokenAt: tokenStart)
        let ranked = counts.sorted { a, b in a.value != b.value ? a.value > b.value : a.key < b.key }
        return ranked.prefix(maxSuggestions).map {
            Suggestion(label: $0.key, insertText: $0.key, kind: .word, detail: "\($0.value)× in this document")
        }
    }

    // MARK: document scans (UTF-8 bytes; only matches become Strings)

    struct OpenEnvironment: Equatable { let name: String; let byte: Int }

    /// One pass for the `\`-token case: environments still open before the
    /// token plus every distinct control word starting with `prefix` (the token
    /// itself excluded).
    static func scanCommands(in text: String, tokenStart: Int, prefix: String) -> (open: [OpenEnvironment], commands: [String]) {
        var stack: [OpenEnvironment] = []
        var commands: [String] = []
        var seen = Set<String>()
        let pre = Array(prefix.utf8)
        withBytes(text) { b in
            forEachCommand(in: b, upTo: b.count) { name, nameStart, arg in
                let byte = nameStart - 1
                if byte < tokenStart, let arg {
                    if bytes(name, equal: "begin") {
                        stack.append(OpenEnvironment(name: String(decoding: arg, as: UTF8.self), byte: byte))
                    } else if bytes(name, equal: "end") {
                        let env = String(decoding: arg, as: UTF8.self)
                        if let i = stack.lastIndex(where: { $0.name == env }) { stack.remove(at: i) }
                    }
                }
                guard byte != tokenStart, name.count >= pre.count,
                      pre.isEmpty || memcmp(name.baseAddress, pre, pre.count) == 0 else { return }
                let word = String(decoding: name, as: UTF8.self)
                if seen.insert(word).inserted { commands.append(word) }
            }
        }
        return (stack, commands)
    }

    /// `\begin{X}` before `byte` with no matching `\end{X}` before it, outermost first.
    static func openEnvironments(in text: String, beforeByte byte: Int) -> [OpenEnvironment] {
        var stack: [OpenEnvironment] = []
        withBytes(text) { b in
            let limit = min(byte, b.count)
            forEachCommand(in: b, upTo: limit) { name, nameStart, arg in
                guard let arg else { return }
                if bytes(name, equal: "begin") {
                    stack.append(OpenEnvironment(name: String(decoding: arg, as: UTF8.self), byte: nameStart - 1))
                } else if bytes(name, equal: "end") {
                    let env = String(decoding: arg, as: UTF8.self)
                    if let i = stack.lastIndex(where: { $0.name == env }) { stack.remove(at: i) }
                }
            }
        }
        return stack
    }

    /// Names of environments appearing in `\begin{…}` anywhere in the document.
    static func documentEnvironments(in text: String) -> [String] {
        var out: [String] = []
        for u in EditorNavigation.uses(in: text as NSString) {
            guard u.name == "begin", let arg = u.arg, !arg.isEmpty else { continue }
            if !out.contains(arg) { out.append(arg) }
        }
        return out
    }

    /// Arguments of `\label{…}` anywhere in the document, in order.
    static func labels(in text: String) -> [String] {
        var out: [String] = []
        withBytes(text) { b in
            forEachCommand(in: b, upTo: b.count) { name, _, arg in
                if let arg, bytes(name, equal: "label") { out.append(String(decoding: arg, as: UTF8.self)) }
            }
        }
        return out
    }

    struct Heading: Equatable { let command: String; let title: String }

    /// The last `\section{…}`/`\subsection{…}` whose backslash lies before
    /// `byte`. The title is the balanced brace group (nested braces allowed,
    /// stops at a newline), so `\section{The \emph{Best} Idea}` is read whole.
    static func enclosingHeading(in text: String, beforeByte byte: Int) -> Heading? {
        var found: Heading?
        withBytes(text) { b in
            guard let p = b.baseAddress else { return }
            forEachCommand(in: b, upTo: min(byte, b.count)) { name, nameStart, _ in
                guard bytes(name, equal: "section") || bytes(name, equal: "subsection") else { return }
                var j = nameStart + name.count
                guard j < b.count, p[j] == UInt8(ascii: "{") else { return }
                j += 1
                var depth = 1
                let start = j
                while j < b.count, depth > 0, p[j] != UInt8(ascii: "\n") {
                    if p[j] == UInt8(ascii: "{") { depth += 1 } else if p[j] == UInt8(ascii: "}") { depth -= 1 }
                    j += 1
                }
                guard depth == 0 else { return }
                let title = String(decoding: UnsafeBufferPointer(start: p + start, count: j - 1 - start), as: UTF8.self)
                found = Heading(command: String(decoding: name, as: UTF8.self), title: title)
            }
        }
        return found
    }

    /// `The \emph{Best} Idea!` → `the-best-idea`: control words and braces are
    /// dropped, letters and digits (any script) are lowercased, every other run
    /// becomes one hyphen, and the result is trimmed.
    static func kebabCase(_ title: String) -> String {
        var cleaned = ""
        var skippingCommand = false
        for ch in title {
            if ch == "\\" { skippingCommand = true; continue }
            if skippingCommand {
                if ch.isLetter { continue }
                skippingCommand = false
            }
            if ch == "{" || ch == "}" { continue }
            cleaned.append(ch)
        }
        var out = ""
        var pendingHyphen = false
        for ch in cleaned.lowercased() {
            if ch.isLetter || ch.isNumber {
                if pendingHyphen, !out.isEmpty { out.append("-") }
                pendingHyphen = false
                out.append(ch)
            } else {
                pendingHyphen = true
            }
        }
        return out
    }

    /// Leading spaces/tabs of the line containing `byte`.
    static func lineIndent(in text: String, beforeByte byte: Int) -> String {
        withBytes(text) { b in
            guard let p = b.baseAddress else { return "" }
            var lineStart = min(byte, b.count)
            while lineStart > 0, p[lineStart - 1] != UInt8(ascii: "\n") { lineStart -= 1 }
            var j = lineStart
            while j < b.count, p[j] == UInt8(ascii: " ") || p[j] == UInt8(ascii: "\t") { j += 1 }
            return String(decoding: UnsafeBufferPointer(start: p + lineStart, count: j - lineStart), as: UTF8.self)
        }
    }

    /// Keys of `\bibitem{…}` anywhere in the document, in order. `\bibitem[x]{key}`
    /// is not matched (the brace does not follow the name); the project index
    /// covers that form.
    static func bibitems(in text: String) -> [String] {
        var out: [String] = []
        withBytes(text) { b in
            forEachCommand(in: b, upTo: b.count) { name, _, arg in
                if let arg, bytes(name, equal: "bibitem") { out.append(String(decoding: arg, as: UTF8.self)) }
            }
        }
        return out
    }

    /// Control words typed anywhere in the document that start with `prefix`,
    /// first occurrence first, excluding the one being typed (whose `\` is at
    /// `excludingTokenAt`).
    static func documentCommands(in text: String, excludingTokenAt tokenStart: Int, prefix: String = "") -> [String] {
        var out: [String] = []
        var seen = Set<String>()
        let pre = Array(prefix.utf8)
        withBytes(text) { b in
            forEachCommand(in: b, upTo: b.count) { name, nameStart, _ in
                guard nameStart - 1 != tokenStart, name.count >= pre.count,
                      pre.isEmpty || memcmp(name.baseAddress, pre, pre.count) == 0 else { return }
                let word = String(decoding: name, as: UTF8.self)
                if seen.insert(word).inserted { out.append(word) }
            }
        }
        return out
    }

    /// Words (letters only, more than 3 characters) starting with `prefix`
    /// (ASCII case-insensitive), counted. The word under the caret is not counted.
    static func wordFrequencies(in text: String, prefix: String, excludingTokenAt tokenStart: Int) -> [String: Int] {
        var counts: [String: Int] = [:]
        let lowered = prefix.utf8.map { c -> UInt8 in (c >= 0x41 && c <= 0x5A) ? c + 0x20 : c }
        guard let lower = lowered.first else { return counts }
        let upper: UInt8 = (lower >= 0x61 && lower <= 0x7A) ? lower - 0x20 : lower
        withBytes(text) { b in
            guard let p = b.baseAddress else { return }
            let table = wordByteClass
            let n = b.count
            // Jump between occurrences of the prefix's first byte (either case) with
            // memchr; only words starting there are walked byte by byte.
            var nextLower = next(lower, in: p, from: 0, count: n)
            var nextUpper = upper == lower ? n : next(upper, in: p, from: 0, count: n)
            while true {
                let start = min(nextLower, nextUpper)
                guard start < n else { break }
                var from = start + 1
                if start == 0 || table[Int(p[start - 1])] == 0 { // at a word start
                    var i = start + 1
                    var ascii = p[start] < 0x80
                    while i < n, table[Int(p[i])] != 0 { if p[i] >= 0x80 { ascii = false }; i += 1 }
                    from = i
                    // Cheap rejections first: length, control words (`\foo`), the token itself.
                    if i - start > 3, start != tokenStart, start == 0 || p[start - 1] != backslash,
                       hasPrefixCaseInsensitive(p, start: start, end: i, prefix: lowered) {
                        let word = String(decoding: UnsafeBufferPointer(start: p + start, count: i - start), as: UTF8.self)
                        // ASCII words are letters by construction; others are checked scalar by scalar.
                        if ascii || (word.unicodeScalars.count > 3 && word.unicodeScalars.allSatisfy({ $0.properties.isAlphabetic })) {
                            counts[word, default: 0] += 1
                        }
                    }
                }
                if nextLower < from { nextLower = next(lower, in: p, from: from, count: n) }
                if nextUpper < from { nextUpper = next(upper, in: p, from: from, count: n) }
            }
        }
        return counts
    }

    // MARK: revision-bound metadata from Rust producers

    /// Completion vocabulary produced by a Rust worker for one exact editor
    /// revision. Everything is bounded (`Limits`) and carries the revision it
    /// was produced for; `bound(to:)` is the only way to obtain metadata for a
    /// caret, and it refuses any other revision.
    struct Metadata: Equatable {
        enum Origin: Equatable {
            /// runtime-v1 `compile_result` for `projectId`.
            case compileResult(projectId: String)
            /// preview-controller `complete` reply, bound to the helper's
            /// per-document `source_versions` map (ledger revisions, not the
            /// editor revision; the caller maps between them).
            case projectIndex(sourceVersions: [String: Int])
        }

        /// One project-index name with its location counts (locations
        /// themselves are not retained; the helper caps them at 100 and flags
        /// truncation, which is preserved).
        struct Item: Equatable {
            let name: String
            let definitions: Int
            let occurrences: Int
            let locationsTruncated: Bool
            /// Project-relative path of the first definition, when any.
            let definedIn: String?

            func detail(noun: String, revision: Int) -> String {
                var s: String
                if definitions == 0 {
                    s = "unresolved in the project index"
                } else {
                    s = "\(noun) in \(definedIn ?? "project")"
                    if definitions > 1 { s += " (+\(definitions - 1) more)" }
                }
                if occurrences > 0 { s += " · \(occurrences)\(locationsTruncated ? "+" : "") use\(occurrences == 1 ? "" : "s")" }
                return s + " · revision \(revision)"
            }
        }

        enum Limits {
            /// Matches the helper's `limit` upper bound and location cap.
            static let maxItemsPerCategory = 100
            /// project-index bounds keys to 4096 bytes; longer names are dropped.
            static let maxNameBytes = 4096
            /// Largest `complete` reply decoded (100 items × 200 locations × ~80 B
            /// is ~1.6 MB; the helper frame limit is 16 MiB).
            static let maxReplyBytes = 4 << 20
            static let maxDiagnostics = 256
            static let maxMessageCharacters = 512
        }

        enum DecodeError: Error, Equatable {
            case tooLarge(bytes: Int)
            case malformed(String)
            /// The reply's `source_versions` differ from the versions the caller
            /// queried with: the helper answered for another snapshot.
            case staleSourceVersions(expected: [String: Int], got: [String: Int])
        }

        let origin: Origin
        /// Editor revision this metadata describes.
        let revision: Int
        var labels: [Item] = []
        var citations: [Item] = []
        var commands: [Item] = []
        /// First diagnostic message naming `\name`, keyed by name (no backslash).
        var diagnosticsByCommand: [String: String] = [:]
        /// `environment 'X' is not implemented; …` messages keyed by `X`.
        var diagnosticsByEnvironment: [String: String] = [:]
        /// Keys from `undefined reference 'key'` diagnostics.
        var unresolvedReferences: Set<String> = []
        /// Some cap in `Limits` dropped data.
        var truncated = false
        /// Document kinds exactly as the helper's `snapshot` reported them
        /// for these `source_versions` (`latex` / `bibliography`), keyed by
        /// project path. Nil when no snapshot was bound (compile-result
        /// metadata, or a helper without `document_kinds`): the kind of a
        /// path is then unknown, never inferred from its name or text.
        var documentKinds: [String: String]?

        /// Whether `path` is a declared bibliography source at this snapshot:
        /// `true`/`false` when the helper reported a kind for exactly that
        /// path, nil when it did not (no snapshot bound, or the path is not
        /// in `document_kinds`) — unknown is never turned into a guess.
        func isDeclaredBibliography(_ path: String?) -> Bool? {
            guard let documentKinds, let path, let kind = documentKinds[path] else { return nil }
            return kind == "bibliography"
        }

        /// Declared bibliography paths at this snapshot (sorted); nil when unknown.
        var declaredBibliographies: [String]? {
            documentKinds.map { $0.filter { $0.value == "bibliography" }.keys.sorted() }
        }

        /// The metadata when it was produced for exactly `revision`, else nil.
        /// A nil `revision` (the editor has not told the view its revision)
        /// binds nothing.
        func bound(to revision: Int?) -> Metadata? {
            guard let revision, revision == self.revision else { return nil }
            return self
        }

        /// Vocabulary from the compiler's own result: only the revision and its
        /// diagnostics carry completion information in runtime-v1.
        static func from(_ result: RuntimeV1.CompileResult) -> Metadata {
            var m = Metadata(origin: .compileResult(projectId: result.projectId), revision: result.revision)
            var used = 0
            for d in result.diagnostics {
                guard used < Limits.maxDiagnostics else { m.truncated = true; break }
                let message = d.message.count > Limits.maxMessageCharacters
                    ? String(d.message.prefix(Limits.maxMessageCharacters)) + "…" : d.message
                if let key = quoted(after: "undefined reference '", in: d.message) {
                    if m.unresolvedReferences.insert(key).inserted { used += 1 }
                } else if let env = quoted(after: "environment '", in: d.message) {
                    if m.diagnosticsByEnvironment[env] == nil { m.diagnosticsByEnvironment[env] = message; used += 1 }
                } else if let bs = d.message.firstIndex(of: "\\") {
                    let name = d.message[d.message.index(after: bs)...].prefix { $0.isASCII && $0.isLetter }
                    if !name.isEmpty, m.diagnosticsByCommand[String(name)] == nil {
                        m.diagnosticsByCommand[String(name)] = message
                        used += 1
                    }
                }
            }
            return m
        }

        /// Decodes a preview-controller `complete` reply payload
        /// (`{"source_versions": {path: revision}, "completions": [...]}`) for
        /// one `category` into metadata bound to `editorRevision`, the editor
        /// revision at which `expectedSourceVersions` was the current snapshot.
        /// A reply for other source versions is refused as stale.
        static func decodeProjectIndexReply(_ data: Data, category: Kind, editorRevision: Int,
                                            expectedSourceVersions: [String: Int]) throws -> Metadata {
            guard data.count <= Limits.maxReplyBytes else { throw DecodeError.tooLarge(bytes: data.count) }
            let reply: ProjectIndexReply
            do { reply = try JSONDecoder().decode(ProjectIndexReply.self, from: data) }
            catch { throw DecodeError.malformed("\(error)") }
            guard reply.sourceVersions == expectedSourceVersions else {
                throw DecodeError.staleSourceVersions(expected: expectedSourceVersions, got: reply.sourceVersions)
            }
            var m = Metadata(origin: .projectIndex(sourceVersions: reply.sourceVersions), revision: editorRevision)
            var items: [Item] = []
            var seen = Set<String>()
            for c in reply.completions {
                guard items.count < Limits.maxItemsPerCategory else { m.truncated = true; break }
                guard c.name.utf8.count <= Limits.maxNameBytes, !c.name.isEmpty else { m.truncated = true; continue }
                guard seen.insert(c.name).inserted else { continue }
                items.append(Item(name: c.name, definitions: c.definitions.count, occurrences: c.occurrences.count,
                                  locationsTruncated: c.locationsTruncated, definedIn: c.definitions.first?.path))
            }
            switch category {
            case .reference: m.labels = items
            case .citation: m.citations = items
            case .command: m.commands = items
            case .environment, .word: throw DecodeError.malformed("project index has no \(category) category")
            }
            return m
        }

        /// Decodes a preview-controller `snapshot` reply payload
        /// (`{"project_id", "source_versions", "membership_generation",
        /// "document_kinds": {path: "latex"|"bibliography"}}`) into metadata
        /// carrying only the declared kinds, bound to `editorRevision`. Refused
        /// (thrown) for other source versions or an unknown kind value; a
        /// reply without `document_kinds` (older helper) binds no kinds.
        static func decodeProjectIndexSnapshot(_ data: Data, editorRevision: Int,
                                               expectedSourceVersions: [String: Int]) throws -> Metadata {
            guard data.count <= Limits.maxReplyBytes else { throw DecodeError.tooLarge(bytes: data.count) }
            let reply: ProjectIndexSnapshot
            do { reply = try JSONDecoder().decode(ProjectIndexSnapshot.self, from: data) }
            catch { throw DecodeError.malformed("\(error)") }
            guard reply.sourceVersions == expectedSourceVersions else {
                throw DecodeError.staleSourceVersions(expected: expectedSourceVersions, got: reply.sourceVersions)
            }
            var m = Metadata(origin: .projectIndex(sourceVersions: reply.sourceVersions), revision: editorRevision)
            if let kinds = reply.documentKinds {
                for (path, kind) in kinds where kind != "latex" && kind != "bibliography" {
                    throw DecodeError.malformed("unknown document kind \(kind) for \(path)")
                }
                m.documentKinds = kinds
            }
            return m
        }

        /// Combines metadata produced for the same revision (compile-result
        /// diagnostics plus one or more project-index categories). Nil when the
        /// revisions differ: metadata never straddles revisions.
        func merged(with other: Metadata) -> Metadata? {
            guard other.revision == revision else { return nil }
            var m = self
            m.labels = Self.union(labels, other.labels)
            m.citations = Self.union(citations, other.citations)
            m.commands = Self.union(commands, other.commands)
            m.diagnosticsByCommand.merge(other.diagnosticsByCommand) { mine, _ in mine }
            m.diagnosticsByEnvironment.merge(other.diagnosticsByEnvironment) { mine, _ in mine }
            m.unresolvedReferences.formUnion(other.unresolvedReferences)
            m.truncated = truncated || other.truncated
            switch (documentKinds, other.documentKinds) {
            case (nil, let k?): m.documentKinds = k
            case (let mine?, let k?): m.documentKinds = mine.merging(k) { mine, _ in mine }
            default: break
            }
            return m
        }

        private static func union(_ a: [Item], _ b: [Item]) -> [Item] {
            var seen = Set(a.map(\.name))
            return a + b.filter { seen.insert($0.name).inserted }
        }

        private static func quoted(after prefix: String, in message: String) -> String? {
            guard let r = message.range(of: prefix) else { return nil }
            let rest = message[r.upperBound...]
            guard let close = rest.firstIndex(of: "'") else { return nil }
            let key = rest[..<close]
            return key.isEmpty ? nil : String(key)
        }

        /// Wire shape of the helper's `snapshot` reply payload (the fields used).
        struct ProjectIndexSnapshot: Decodable {
            let sourceVersions: [String: Int]
            let documentKinds: [String: String]?
            enum CodingKeys: String, CodingKey { case sourceVersions = "source_versions", documentKinds = "document_kinds" }
        }

        /// Wire shape of the helper's `complete` reply payload.
        struct ProjectIndexReply: Decodable {
            struct Location: Decodable {
                let path: String
                let revision: Int
                let startByte: Int
                let endByte: Int
                enum CodingKeys: String, CodingKey { case path, revision, startByte = "start_byte", endByte = "end_byte" }
            }
            struct Item: Decodable {
                let name: String
                let definitions: [Location]
                let occurrences: [Location]
                let locationsTruncated: Bool
                enum CodingKeys: String, CodingKey { case name, definitions, occurrences, locationsTruncated = "locations_truncated" }
            }
            let sourceVersions: [String: Int]
            let completions: [Item]
            enum CodingKeys: String, CodingKey { case sourceVersions = "source_versions", completions }
        }
    }

    // MARK: byte helpers

    static let backslash = UInt8(ascii: "\\")

    /// 256-entry table: 1 for ASCII letters, 2 for every non-ASCII byte
    /// (multi-byte scalars stay whole; matches are re-checked as alphabetic
    /// scalars before use), 0 otherwise. A raw pointer keeps debug-build
    /// scans free of array bounds checks and retain/release traffic.
    static let wordByteClass: UnsafePointer<UInt8> = {
        let table = UnsafeMutablePointer<UInt8>.allocate(capacity: 256)
        for c in 0..<256 {
            let letter = (c >= 0x41 && c <= 0x5A) || (c >= 0x61 && c <= 0x7A)
            table[c] = letter ? 1 : (c >= 0x80 ? 2 : 0)
        }
        return UnsafePointer(table)
    }()

    static func isWordByte(_ c: UInt8) -> Bool { wordByteClass[Int(c)] != 0 }

    /// Index of the next `byte` at or after `from`, or `n` (vectorised libc scan).
    @inline(__always) static func next(_ byte: UInt8, in p: UnsafePointer<UInt8>, from: Int, count n: Int) -> Int {
        guard from < n, let hit = memchr(p + from, Int32(byte), n - from) else { return n }
        return UnsafePointer<UInt8>(hit.assumingMemoryBound(to: UInt8.self)) - p
    }

    @inline(__always) static func nextBackslash(_ p: UnsafePointer<UInt8>, from: Int, count n: Int) -> Int {
        next(backslash, in: p, from: from, count: n)
    }

    /// Calls `body` for each control word `\name` (and its `{arg}` when one
    /// immediately follows) whose backslash lies before `limit`.
    /// `name` is the control word's bytes (decode with `String(decoding:as:)`
    /// only when needed — most callers compare against a few literals first).
    static func forEachCommand(in b: UnsafeBufferPointer<UInt8>, upTo limit: Int,
                               _ body: (_ name: UnsafeBufferPointer<UInt8>, _ nameStart: Int, _ arg: UnsafeBufferPointer<UInt8>?) -> Void) {
        guard let p = b.baseAddress else { return }
        let n = min(limit, b.count), total = b.count
        let table = wordByteClass
        var i = nextBackslash(p, from: 0, count: n)
        while i < n {
            let nameStart = i + 1
            var j = nameStart
            while j < total, table[Int(p[j])] == 1 { j += 1 }
            guard j > nameStart else { i = nextBackslash(p, from: min(j + 1, total), count: n); continue } // `\\`, `\{`, …
            let name = UnsafeBufferPointer(start: p + nameStart, count: j - nameStart)
            var arg: UnsafeBufferPointer<UInt8>?
            if j < total, p[j] == UInt8(ascii: "{") {
                var k = j + 1
                while k < total, p[k] != UInt8(ascii: "}"), p[k] != UInt8(ascii: "{"), p[k] != backslash,
                      p[k] != UInt8(ascii: "\n") { k += 1 }
                if k < total, p[k] == UInt8(ascii: "}") {
                    arg = UnsafeBufferPointer(start: p + j + 1, count: k - j - 1)
                    j = k + 1
                }
            }
            body(name, nameStart, arg)
            i = nextBackslash(p, from: j, count: n)
        }
    }

    @inline(__always) static func bytes(_ b: UnsafeBufferPointer<UInt8>, equal literal: StaticString) -> Bool {
        b.count == literal.utf8CodeUnitCount && memcmp(b.baseAddress, literal.utf8Start, b.count) == 0
    }

    private static func endsWith(_ b: UnsafeBufferPointer<UInt8>, upTo end: Int, suffix: String) -> Bool {
        let s = Array(suffix.utf8)
        guard end >= s.count else { return false }
        for (k, c) in s.enumerated() where b[end - s.count + k] != c { return false }
        return true
    }

    private static func hasPrefixCaseInsensitive(_ p: UnsafePointer<UInt8>, start: Int, end: Int, prefix: [UInt8]) -> Bool {
        guard end - start >= prefix.count else { return false }
        var k = 0
        while k < prefix.count {
            var c = p[start + k]
            if c >= 0x41 && c <= 0x5A { c += 0x20 }
            if c != prefix[k] { return false }
            k += 1
        }
        return true
    }

    /// UTF-8 offset of a UTF-16 caret, or nil when out of range or inside a
    /// surrogate pair.
    static func utf8Offset(of caretUTF16: Int, in text: String) -> Int? {
        // A negative location traps inside Foundation; past-the-end and
        // surrogate-interior locations already come back as nil. Avoid
        // `utf16.count`, which is O(n) on a freshly built native string.
        guard caretUTF16 >= 0 else { return nil }
        return text.utf8ByteRange(of: NSRange(location: caretUTF16, length: 0))?.start
    }

    /// Runs `body` over the string's UTF-8 bytes without copying when the
    /// string is already contiguous (native Swift strings are).
    static func withBytes<R>(_ text: String, _ body: (UnsafeBufferPointer<UInt8>) -> R) -> R {
        var copy = text
        return copy.withUTF8(body)
    }
}

// MARK: - Project-index vocabulary through the preview-controller helper

/// Drives the helper's `complete` queries (STDIO.md) for the three categories
/// plus the `snapshot` (declared document kinds) at one exact snapshot and
/// turns the replies into one bound `Metadata`.
/// Owned by the shell model, which calls `request` when a controller preview
/// for known `source_versions` was applied and routes `result`/`error` frames
/// through `handle`. Everything is refused rather than guessed: a reply for
/// other source versions, a helper error (e.g. "source versions changed"), or
/// a newer request all discard the query. Nothing here blocks: `send` only
/// writes a frame.
@MainActor
final class ProjectIndexCompletionFetcher {
    static let categories: [Completion.Kind] = [.reference, .citation, .command]
    static let wireCategory: [Completion.Kind: String] = [.reference: "label", .citation: "citation", .command: "command"]

    /// One reply the query waits for: a `complete` category or the `snapshot`
    /// that names the document kinds of the same source versions.
    enum Part: Equatable { case category(Completion.Kind), documentKinds }

    struct Query: Equatable {
        /// Request id → part, for the replies still outstanding.
        var outstanding: [String: Part]
        let sourceVersions: [String: Int]
        let editorRevision: Int
        var merged: Completion.Metadata?
        /// `MonotonicClock` stamp of `request`, for request → metadata latency.
        var requestedNs: UInt64 = 0
    }

    enum Outcome: Equatable {
        /// The id does not belong to this fetcher.
        case notMine
        /// Accepted; other categories are still outstanding.
        case pending
        /// Every category arrived: metadata bound to the query's editor revision.
        case complete(Completion.Metadata)
        /// The query was discarded (stale versions, helper error, decode failure).
        case refused(String)
    }

    private(set) var query: Query?
    private(set) var refusals = 0
    /// Request → complete metadata wall time of the last completed query.
    private(set) var lastLatencyMs: Double?

    /// Sends one `complete` per category with an empty prefix and the maximum
    /// limit (100), plus one `snapshot` for the declared document kinds, all
    /// naming the exact `sourceVersions` the preview was compiled from and the
    /// editor revision that produced them. A previous query is discarded. A
    /// send failure discards the whole query.
    func request(sourceVersions: [String: Int], editorRevision: Int,
                 send: (_ type: String, _ payload: [String: Any]) throws -> String) {
        var outstanding: [String: Part] = [:]
        for kind in Self.categories {
            let payload: [String: Any] = ["source_versions": sourceVersions, "category": Self.wireCategory[kind]!,
                                          "prefix": "", "limit": Completion.Metadata.Limits.maxItemsPerCategory]
            guard let id = try? send("complete", payload) else { query = nil; return }
            outstanding[id] = .category(kind)
        }
        guard let kindsID = try? send("snapshot", [:]) else { query = nil; return }
        outstanding[kindsID] = .documentKinds
        query = Query(outstanding: outstanding, sourceVersions: sourceVersions, editorRevision: editorRevision, merged: nil,
                      requestedNs: MonotonicClock.nowNs())
    }

    /// A `result` frame. The payload is the helper's JSON object; it is
    /// re-serialized so the bounded decoder sees the documented wire shape.
    func handle(resultID id: String, payload: [String: Any]) -> Outcome {
        guard var q = query, let part = q.outstanding[id] else { return .notMine }
        let data: Data
        do { data = try JSONSerialization.data(withJSONObject: payload) } catch { return refuse("unserializable reply \(id)") }
        let metadata: Completion.Metadata
        do {
            switch part {
            case .category(let kind):
                metadata = try Completion.Metadata.decodeProjectIndexReply(data, category: kind, editorRevision: q.editorRevision,
                                                                           expectedSourceVersions: q.sourceVersions)
            case .documentKinds:
                metadata = try Completion.Metadata.decodeProjectIndexSnapshot(data, editorRevision: q.editorRevision,
                                                                              expectedSourceVersions: q.sourceVersions)
            }
        } catch {
            return refuse("\(part) reply \(id): \(error)")
        }
        q.outstanding.removeValue(forKey: id)
        q.merged = q.merged.flatMap { $0.merged(with: metadata) } ?? metadata
        if q.outstanding.isEmpty, let merged = q.merged {
            query = nil
            lastLatencyMs = Double(MonotonicClock.nowNs() - q.requestedNs) / 1e6
            return .complete(merged)
        }
        query = q
        return .pending
    }

    /// The helper is gone (exit, detach): its outstanding ids mean nothing on
    /// the next client, whose ids restart at `pc-1`; forget the query so a
    /// colliding id cannot claim an unrelated reply.
    func discard() { query = nil }

    /// An `error` frame for one of the query's ids discards the query.
    func handle(errorID id: String?, message: String) -> Outcome {
        guard let id, let q = query, q.outstanding[id] != nil else { return .notMine }
        return refuse("helper error for \(id): \(message)")
    }

    private func refuse(_ why: String) -> Outcome {
        query = nil
        refusals += 1
        return .refused(why)
    }
}

// MARK: - Off-main candidate computation

/// Computes candidates off the main thread and delivers them on the main run
/// loop only while the request is still current. `cancel()` (every text change
/// or caret move) and any newer `schedule` invalidate the pending job: its
/// result is refused at delivery and never reaches the view. The keystroke
/// path therefore only copies the text and enqueues; it never scans.
@MainActor
final class CompletionScheduler {
    struct Request {
        var text: String
        var caretUTF16: Int
        /// Already bound to the revision of `text` (`Metadata.bound(to:)`).
        var metadata: Completion.Metadata?
        var supported: [String] = Completion.defaultSupported
        /// Project document paths offered after `\input{`, `\include{` and `\includegraphics{`.
        var projectFiles: [String] = []
        /// Whether the caret is in math mode (`Completion.isMathMode`), decided
        /// on the main thread where the editor's syntax model is in sync.
        var mathMode = false
    }

    struct Outcome: Equatable {
        let generation: Int
        let caretUTF16: Int
        /// UTF-16 range the items replace, computed from the request's text.
        let range: NSRange
        let items: [Completion.Suggestion]
        /// Wall time of the off-main scan.
        let computeMs: Double
        /// Time the job waited on the queue before the scan started.
        var queuedMs: Double = 0
        /// `MonotonicClock` stamp taken when the scan finished, so the
        /// consumer can measure the run-loop delivery lag.
        var computedAtNs: UInt64 = 0
    }

    struct Statistics: Equatable {
        var scheduled = 0
        /// Outcomes handed to the caller.
        var delivered = 0
        /// Outcomes that reached the main thread after their job was cancelled
        /// or superseded, and were dropped.
        var refusedStale = 0
        /// Jobs cancelled (explicitly or by a newer request) before delivery.
        var cancelled = 0
    }

    /// Runs one job somewhere off the main thread. The default is a serial
    /// user-initiated queue; tests inject an executor that holds jobs so the
    /// order of caret moves and job completion is deterministic.
    typealias Executor = (@escaping @Sendable () -> Void) -> Void

    /// Cancellation flag shared with the running job; polled between scan phases.
    final class Job: @unchecked Sendable {
        let generation: Int
        private let cancelledFlag = OSAllocatedUnfairLock(initialState: false)
        init(generation: Int) { self.generation = generation }
        var isCancelled: Bool { cancelledFlag.withLock { $0 } }
        func cancel() { cancelledFlag.withLock { $0 = true } }
    }

    private(set) var generation = 0
    private(set) var statistics = Statistics()
    private(set) var pending: Job?
    private let execute: Executor

    init(executor: Executor? = nil) {
        if let executor {
            execute = executor
        } else {
            let queue = DispatchQueue(label: "flashtex.completion", qos: .userInitiated)
            execute = { queue.async(execute: $0) }
        }
    }

    /// Enqueues `request`; `deliver` runs on the main run loop with the outcome
    /// unless the job was cancelled or superseded first. Returns the job's
    /// generation.
    @discardableResult
    func schedule(_ request: Request, deliver: @escaping @MainActor (Outcome) -> Void) -> Int {
        cancelPending()
        generation += 1
        let job = Job(generation: generation)
        pending = job
        statistics.scheduled += 1
        let scheduledAt = MonotonicClock.nowNs()
        execute { [weak self] in
            let t0 = MonotonicClock.nowNs()
            let range = Completion.completionRange(in: request.text, caretUTF16: request.caretUTF16)
            let items = job.isCancelled ? [] : Completion.suggestions(in: request.text, caretUTF16: request.caretUTF16,
                                                                     metadata: request.metadata, supported: request.supported,
                                                                     projectFiles: request.projectFiles, mathMode: request.mathMode,
                                                                     cancelled: { job.isCancelled })
            let t1 = MonotonicClock.nowNs()
            let outcome = Outcome(generation: job.generation, caretUTF16: request.caretUTF16, range: range, items: items,
                                  computeMs: Double(t1 - t0) / 1e6, queuedMs: Double(t0 - scheduledAt) / 1e6, computedAtNs: t1)
            Self.onMain { [weak self] in
                MainActor.assumeIsolated { [weak self] in
                    guard let self else { return }
                    // Stale refusal: only the exact current, uncancelled job is delivered.
                    guard !job.isCancelled, job.generation == self.generation, self.pending === job else {
                        self.statistics.refusedStale += 1
                        return
                    }
                    self.pending = nil
                    self.statistics.delivered += 1
                    deliver(outcome)
                }
            }
        }
        return job.generation
    }

    /// Invalidates the pending job (if any) and every outcome computed so far.
    func cancel() {
        cancelPending()
        generation += 1
    }

    private func cancelPending() {
        guard let job = pending, !job.isCancelled else { return }
        job.cancel()
        statistics.cancelled += 1
        pending = nil
    }

    /// Head-of-run-loop delivery (see `WorkerClient.deliver`): a plain
    /// `DispatchQueue.main.async` waits for AppKit to reach the dispatch port.
    nonisolated private static func onMain(_ block: @escaping @Sendable () -> Void) {
        CFRunLoopPerformBlock(CFRunLoopGetMain(), CFRunLoopMode.commonModes.rawValue, block)
        CFRunLoopWakeUp(CFRunLoopGetMain())
    }
}

