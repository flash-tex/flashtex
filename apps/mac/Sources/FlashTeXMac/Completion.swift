    /// Synchronous candidates for `charRange` (bound metadata only). The popup
    /// never uses this path; it exists for AppKit callers and tests.
    override func completions(forPartialWordRange charRange: NSRange,
                              indexOfSelectedItem index: UnsafeMutablePointer<Int>) -> [String]? {
        index.pointee = 0
        // The range came from `rangeForUserCompletion`; the text may have changed
        // since (or the caller may pass anything). Never index past the string.
        let text = string
        guard charRange.location != NSNotFound, charRange.location >= 0, charRange.length >= 0,
              NSMaxRange(charRange) <= (text as NSString).length else { return nil }
        let items = Completion.suggestions(in: text, caretUTF16: NSMaxRange(charRange), metadata: boundMetadata,
                                          supported: supportedCommands)
        return items.isEmpty ? nil : items.map(\.insertText)
    }

    /// AppKit calls this with the chosen string; the default implementation
    /// replaces `charRange`. Guard the range the same way so a stale range can
    /// never splice text at the wrong place.
    override func insertCompletion(_ word: String, forPartialWordRange charRange: NSRange,
                                   movement: Int, isFinal flag: Bool) {
        guard charRange.location != NSNotFound, charRange.location >= 0, charRange.length >= 0,
              NSMaxRange(charRange) <= (string as NSString).length else { return }
        super.insertCompletion(word, forPartialWordRange: charRange, movement: movement, isFinal: flag)
    }

    // MARK: session lifecycle

    /// Esc (AppKit's `cancelOperation:` → `complete:`) and ⌃Space land here.
    override func complete(_ sender: Any?) { requestCompletion() }

    /// Copies the text and enqueues the scan; the popup opens (or refreshes)
    /// when the outcome is delivered and still current.
    func requestCompletion() {
        guard EditorPreferences.shared.completionPopup else { return } // preference: list disabled
        observeStorageIfNeeded()
        let caret = selectedRange()
        guard caret.length == 0, !hasMarkedText() else { return }
        lastCaret = caret
        let metadata = boundMetadata
        let request = CompletionScheduler.Request(text: string, caretUTF16: caret.location, metadata: metadata,
                                                  supported: supportedCommands, projectFiles: projectFiles,
                                                  mathMode: mathModeAtCaret(caret.location))
        scheduler.schedule(request) { [weak self] outcome in
            self?.present(outcome, metadataRevision: metadata?.revision)
        }
        // First use: build the panel now, while the scan runs off-main, so the
        // delivery path only has to fill and show it.
        if session == nil { _ = popup }
    }

    private func present(_ outcome: CompletionScheduler.Outcome, metadataRevision: Int?) {
        let t0 = MonotonicClock.nowNs()
        lastOutcome = outcome
        lastDeliveryLagMs = outcome.computedAtNs == 0 ? 0 : Double(t0 &- outcome.computedAtNs) / 1e6
        defer { lastPresentMs = Double(MonotonicClock.nowNs() - t0) / 1e6 }
        // The scheduler refused other generations; the caret must also still
        // be where the request was made and the range must fit the text.
        let caret = selectedRange()
        guard caret.length == 0, caret.location == outcome.caretUTF16,
              NSMaxRange(outcome.range) <= (string as NSString).length else { return }
        guard !outcome.items.isEmpty else {
            if session != nil { close(.noCandidates) }
            return
        }
        var selected = 0
        if let current = session?.selected, let i = outcome.items.firstIndex(where: { $0.label == current.label }) {
            selected = i // the same item stays chosen while typing narrows the list
        }
        session = CompletionSession(items: outcome.items, range: outcome.range, selectedIndex: selected,
                                    generation: outcome.generation, metadataRevision: metadataRevision)
        showPopup()
    }

    private func showPopup() {
        guard let session, let window else { return }
        let caretRect = firstRect(forCharacterRange: NSRange(location: selectedRange().location, length: 0), actualRange: nil)
        popup.show(items: session.items, selected: session.selectedIndex, below: caretRect, parent: window)
    }

    func close(_ reason: CloseReason) {
        lastCloseReason = reason
        if reason == .escape { suppressAutomaticCompletionForCurrentToken() } else { cancelAutomaticCompletion() }
        guard session != nil else { return }
        session = nil
        popup.hide()
    }

    func moveSelection(by delta: Int) {
        guard let s = session, !s.items.isEmpty else { return }
        selectCompletion(at: (s.selectedIndex + delta + s.items.count) % s.items.count)
    }

    /// Drops the session's selection (to an index no item has) so tests can
    /// check that a list with nothing selected hands keys back to the editor
    /// instead of eating them. No app path produces this state today; the
    /// guard in `keyDown` exists so a future one cannot swallow Return.
    func dropSessionSelectionForTesting() {
        guard var s = session else { return }
        s.selectedIndex = -1
        session = s
    }

    func selectCompletion(at index: Int) {
        guard var s = session, s.items.indices.contains(index) else { return }
        s.selectedIndex = index
        session = s
        popup.update(items: s.items, selected: index)
    }

    /// The list window (created on first use), for tests and evidence.
    var completionPopup: CompletionPopup { popup }

    /// Replaces the session's range with the selected item, as one undoable
    /// edit, and closes the list. Refused when the text or caret changed since
    /// the items were computed.
    func acceptSelectedCompletion() {
        guard let s = session, let item = s.selected else { return }
        guard !hasMarkedText() else { return } // IME composition owns the text until it ends
        guard s.generation == scheduler.generation, NSMaxRange(s.range) <= (string as NSString).length,
              selectedRange() == NSRange(location: NSMaxRange(s.range), length: 0) else {
            close(.textChanged)
            return
        }
        applyingCompletion = true
        let range = rangeConsumingStaleCloser(s.range, inserting: item.snippet?.text ?? item.insertText)
        if let snippet = item.snippet {
            insertSnippet(snippet, replacing: range, kind: item.kind)
        } else if range.length != s.range.length {
            // AppKit's `insertCompletion` recomputes the range it replaces from
            // `rangeForUserCompletion` (the bare token) instead of using the one
            // it is handed, so a grown range never reaches the storage through
            // it — measured: the stale `}` survived as `\end{itemize}}`. This
            // one goes in directly, with the same effect and one undo step.
            insertPlainCompletion(item.insertText, replacing: range)
        } else {
            insertCompletion(item.insertText, forPartialWordRange: range, movement: NSReturnTextMovement, isFinal: true)
        }
        applyingCompletion = false
        scheduler.cancel()
        close(.accepted)
    }

    /// The session range, grown by one unit when an auto-inserted closer sits
    /// immediately after it and `inserted` supplies that closer itself. Without
    /// this the editor's `}` survives the replacement and strands itself past
    /// the completion: `\begin{` auto-closes, `proof` is accepted as
    /// `proof}\n\n\end{proof}`, and the buffer ends `\end{proof}}` (GH#2).
    /// Only offsets the editor is still tracking are eaten, so a brace the user
    /// typed is never removed and `pendingClosers` keeps its invariant: every
    /// tracked offset points at a closer this editor inserted and the user has
    /// not yet passed (the delegate drops this one as the edit overlaps it).
    private func rangeConsumingStaleCloser(_ range: NSRange, inserting inserted: String) -> NSRange {
        let end = NSMaxRange(range)
        let ns = string as NSString
        guard end < ns.length, isPendingCloser?(end) == true,
              let closer = ns.substring(with: NSRange(location: end, length: 1)).first,
              EditorKeyHandling.supersedesTrackedCloser(inserted, closer: closer) else { return range }
        return NSRange(location: range.location, length: range.length + 1)
    }

    /// What `insertCompletion(_:forPartialWordRange:movement:isFinal:)` does —
    /// replace the range, leave the caret after the word, one undo step — for
    /// the range this view chose rather than the one AppKit would recompute.
    private func insertPlainCompletion(_ word: String, replacing range: NSRange) {
        breakUndoCoalescing()
        guard shouldChangeText(in: range, replacementString: word) else { return }
        textStorage?.replaceCharacters(in: range, with: word)
        didChangeText() // registers the undo step, fires textDidChange
        undoManager?.setActionName("Insert Completion")
        setSelectedRange(NSRange(location: range.location + (word as NSString).length, length: 0))
        breakUndoCoalescing()
    }

    /// One undo step: the typed partial token is closed off first so ⌘Z
    /// removes exactly the snippet and restores the token.
    private func insertSnippet(_ snippet: Completion.Snippet, replacing range: NSRange, kind: Completion.Kind) {
        breakUndoCoalescing()
        guard shouldChangeText(in: range, replacementString: snippet.text) else { return }
        textStorage?.replaceCharacters(in: range, with: snippet.text)
        didChangeText() // registers the undo step, fires textDidChange
        undoManager?.setActionName(kind == .environment ? "Insert Environment" : "Insert Snippet")
        let caret = range.location + snippet.caretUTF16
        setSelectedRange(NSRange(location: caret, length: 0))
        breakUndoCoalescing()
        // Tab stops (absolute) for the placeholders after the caret's.
        snippetStart = range.location + snippet.caretUTF16
        snippetStops = snippet.stops.map { range.location + $0 }
        snippetStopIndex = -1
        lastCaret = selectedRange()
        refreshSignatureHelp(open: true) // `\frac{|}{}`: the argument pattern is useful right away
        if let offset = EditorKeyHandling.programmaticCloser(in: snippet.text, insertedAt: range.location, caretUTF16: caret) {
            onCloserInserted?(offset) // e.g. `\section{}`'s `}` overtypes instead of doubling
        }
    }

